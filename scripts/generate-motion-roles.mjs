/**
 * @file generate-motion-roles.mjs
 * @description Writes the table of touch motion roles in
 *   packages/cli/assets/docs/motion.doc.mjs (between the motion-roles
 *   markers) from the motion tables themselves: every spring, duration and
 *   curve of a table that calls `registerMotionTable`, with its CSS variable
 *   and its measured default. The tables stay the one source of the values.
 *   Also writes packages/core/src/motion/roleKinds.generated.ts, every role id
 *   with its kind, so a theme's role ids are checked without importing the
 *   tables.
 *
 * Both are written Prettier-formatted, so `prettier --check` agrees.
 *
 * Run: node scripts/generate-motion-roles.mjs
 * CI:  `node scripts/generate-motion-roles.mjs --check` fails on drift.
 */
import {readFileSync, readdirSync, writeFileSync} from 'node:fs';
import {dirname, join, relative, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';
import * as prettier from 'prettier';
import {motionTableFiles, REGISTER_EXPORT} from './motion-table-files.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CORE_SRC = resolve(ROOT, 'packages/core/src');
const ROLES = resolve(CORE_SRC, 'motion/roles.ts');
const DOC = resolve(ROOT, 'packages/cli/assets/docs/motion.doc.mjs');
const KINDS = resolve(CORE_SRC, 'motion/roleKinds.generated.ts');
const START =
  '// motion-roles:start (generated by scripts/generate-motion-roles.mjs)';
const END = '// motion-roles:end';

async function roleRows() {
  const files = motionTableFiles(CORE_SRC);
  const entry = [
    `import {listMotionRoles, formatMotionRoleValue} from ${JSON.stringify(ROLES)};`,
    ...files.map(
      (file, i) => `import * as table${i} from ${JSON.stringify(file)};`,
    ),
    // Every register<Name>Table export, so the list holds every table.
    `for (const module of [${files.map((_, i) => `table${i}`).join(', ')}]) {`,
    `  for (const [name, value] of Object.entries(module)) {`,
    `    if (${REGISTER_EXPORT}.test(name) && typeof value === 'function') value();`,
    '  }',
    '}',
    'export const rows = listMotionRoles().map(role => [role.id, role.variable, role.kind, formatMotionRoleValue(role.kind, role.value)]);',
  ].join('\n');
  const result = await build({
    stdin: {contents: entry, resolveDir: CORE_SRC, loader: 'ts'},
    bundle: true,
    format: 'esm',
    platform: 'node',
    write: false,
    // A legacy table that still registers on import keeps that import, even
    // though the package declares itself free of side effects.
    ignoreAnnotations: true,
    logLevel: 'silent',
  });
  const code = result.outputFiles[0].text;
  const mod = await import(
    `data:text/javascript;base64,${Buffer.from(code).toString('base64')}`
  );
  return {rows: mod.rows, files};
}

function render(rows, indent) {
  return rows
    .map(row => `${indent}[${row.map(cell => `'${cell}'`).join(', ')}],`)
    .join('\n');
}

const check = process.argv.includes('--check');
const {rows, files} = await roleRows();
const text = readFileSync(DOC, 'utf8');
const start = text.indexOf(START);
const end = text.indexOf(END);
if (start < 0 || end < start) {
  console.error(
    `${relative(ROOT, DOC)}: the motion-roles markers are missing.`,
  );
  process.exit(1);
}
const lineStart = text.lastIndexOf('\n', start) + 1;
const indent = text.slice(lineStart, start);
const next = await prettier.format(
  `${text.slice(0, start)}${START}\n${render(rows, indent)}\n${indent}${text.slice(end)}`,
  {...(await prettier.resolveConfig(DOC)), filepath: DOC},
);
const kinds = await prettier.format(
  [
    '// Copyright (c) Meta Platforms, Inc. and affiliates.',
    '// @generated by scripts/generate-motion-roles.mjs; do not edit.',
    '',
    '/**',
    ' * @file roleKinds.generated.ts',
    ' * @input The motion tables that call registerMotionTable',
    ' * @output MOTION_ROLE_KINDS, every motion role id with its kind',
    ' * @position Lets defineTheme check a role id and its kind without importing',
    ' *   the tables (theme/expandMotionRoles.ts)',
    ' */',
    '',
    "import type {MotionRoleKind} from './roles';",
    '',
    'export const MOTION_ROLE_KINDS: Readonly<Record<string, MotionRoleKind>> = {',
    ...rows.map(
      ([id, , kind]) => `  ${JSON.stringify(id)}: ${JSON.stringify(kind)},`,
    ),
    '};',
    '',
  ].join('\n'),
  {...(await prettier.resolveConfig(KINDS)), filepath: KINDS},
);
const kindsBefore = (() => {
  try {
    return readFileSync(KINDS, 'utf8');
  } catch {
    return '';
  }
})();

if (check) {
  const stale = [
    next !== text && relative(ROOT, DOC),
    kinds !== kindsBefore && relative(ROOT, KINDS),
  ].filter(Boolean);
  if (stale.length > 0) {
    console.error(
      `${stale.join(' and ')}: out of date with the motion tables; run node scripts/generate-motion-roles.mjs.`,
    );
    process.exit(1);
  }
  console.log(
    `✓ The motion role table and role kinds are up to date (${rows.length} roles, ${new Set(rows.map(row => row[0].split('.')[0])).size} tables).`,
  );
} else {
  writeFileSync(DOC, next);
  writeFileSync(KINDS, kinds);
  console.log(
    `Wrote ${rows.length} motion roles from ${new Set(rows.map(row => row[0].split('.')[0])).size} tables to ${relative(ROOT, DOC)} and ${relative(ROOT, KINDS)}.`,
  );
}
