/**
 * @file lab-sync.mjs
 * @input The Lab package's component docs (`packages/lab/src/**\/*.doc.mjs`)
 *   and block docs (`packages/lab/blocks/*.doc.mjs`), the shadcn route lock
 *   (`internal/shadcn-registry/routes.lock.json`) and the Lab swizzle samples
 *   (`packages/lab/swizzle-samples.mjs`).
 * @output `pnpm lab:sync` writes each Lab component's, hook's, example's and
 *   showcase's route-lock entry, and a swizzle sample stub for a Lab target
 *   whose doc names a required prop with no default and that has no sample.
 *   It never changes an existing sample. `--check` writes nothing; it names
 *   each missing entry and exits 1.
 * @position Run by hand after adding a Lab component, by `pnpm preflight`, and
 *   by CI's Lab lane. Names and paths come from the docsite's own registry
 *   identity helpers (apps/docsite/src/lib/shadcnRegistry.mjs), so they match
 *   what the docsite generator writes.
 */
/* global console, process */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LAB = '@astryxdesign/lab';
export const ROUTE_LOCK = 'internal/shadcn-registry/routes.lock.json';
export const LAB_SAMPLES = 'packages/lab/swizzle-samples.mjs';
/** The line in LAB_SAMPLES that new stubs go above. */
export const STUB_MARKER = '  // lab:sync adds new samples above this line.';
export const STUB_NOTE = '// generated by lab:sync; edit freely';

// Each pass reads the samples file afresh; a URL Node has seen is cached.
let reads = 0;

async function loadDoc(file) {
  const m = await import(pathToFileURL(file).href);
  return (
    m.doc ??
    m.default ??
    Object.values(m).find(v => v && typeof v === 'object' && v.name) ??
    null
  );
}

function docFiles(dir, recursive) {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir, {recursive})
    .map(String)
    .filter(file => file.endsWith('.doc.mjs'))
    .sort();
}

/**
 * The route-lock entries the Lab docs give, by the docsite generator's own
 * rules: a sub-component doc is its own entry; a family doc gives each
 * documented sub-component (a name-only reference is not one), and itself
 * when it has top-level props; any other doc gives itself. A name starting
 * with `use`, or an entry with params, is a hook. Each Lab block gives an
 * example or a showcase of the component it is for.
 * @param {string} root the repository
 * @param {{componentRegistryIdentity: Function, blockRegistryIdentity: Function}} identity
 * @returns {Promise<{name: string, path: string, aliases: string[]}[]>}
 */
export async function labRouteEntries(root, identity) {
  const entries = new Map();
  const add = id =>
    entries.set(id.name, {name: id.name, path: id.path, aliases: id.aliases});
  const strip = name => String(name || '').replace(/^XDS/, '');
  const src = path.join(root, 'packages/lab/src');
  for (const file of docFiles(src, true)) {
    const doc = await loadDoc(path.join(src, file));
    if (!doc) continue;
    if (doc.subComponentOf) {
      const name = strip(doc.name);
      if (!name) continue;
      const hook =
        name.startsWith('use') ||
        Array.isArray(doc.params) ||
        Array.isArray(doc.returns);
      add(
        identity.componentRegistryIdentity(
          LAB,
          name,
          hook,
          doc.registry ?? null,
        ),
      );
    } else if (Array.isArray(doc.components) && doc.components.length > 0) {
      if (Array.isArray(doc.props) && doc.props.length > 0) {
        const name = doc.name || strip(path.basename(file, '.doc.mjs'));
        add(
          identity.componentRegistryIdentity(
            LAB,
            name,
            false,
            doc.registry ?? null,
          ),
        );
      }
      for (const sub of doc.components) {
        const raw = sub?.name || '';
        const name = strip(raw);
        if (!name || (Object.keys(sub).length === 1 && sub.name != null))
          continue;
        const hook =
          raw.startsWith('use') ||
          name.startsWith('use') ||
          Array.isArray(sub.params);
        add(
          identity.componentRegistryIdentity(
            LAB,
            name,
            hook,
            sub.registry ?? doc.registry ?? null,
          ),
        );
      }
    } else {
      const name = strip(doc.name);
      if (!name) continue;
      const hook = name.startsWith('use') || Array.isArray(doc.params);
      add(
        identity.componentRegistryIdentity(
          LAB,
          name,
          hook,
          doc.registry ?? null,
        ),
      );
    }
  }
  const blocks = path.join(root, 'packages/lab/blocks');
  for (const file of docFiles(blocks, false)) {
    const doc = await loadDoc(path.join(blocks, file));
    if (!doc?.name) continue;
    add(
      identity.blockRegistryIdentity(
        doc.name,
        doc.exampleFor ?? null,
        doc.isShowcase ?? false,
        doc.registry ?? null,
      ),
    );
  }
  return [...entries.values()];
}

/**
 * The route lock with every Lab entry present and current. Other entries
 * stay as they are; the items keep the generator's order (by path).
 * @param {string} lockText the lock file's text
 * @param {{name: string, path: string, aliases: string[]}[]} entries
 * @returns {{text: string, missing: string[]}} `missing` names each entry
 *   added or changed
 */
export function syncRouteLock(lockText, entries) {
  const lock = JSON.parse(lockText);
  const byName = new Map(lock.items.map(item => [item.name, item]));
  const missing = [];
  for (const entry of entries) {
    if (JSON.stringify(byName.get(entry.name)) === JSON.stringify(entry))
      continue;
    missing.push(entry.name);
    byName.set(entry.name, entry);
  }
  if (missing.length === 0) return {text: lockText, missing};
  const items = [...byName.values()].sort((a, b) =>
    a.path.localeCompare(b.path),
  );
  return {
    text: `${JSON.stringify({...lock, items}, null, 2)}\n`,
    missing,
  };
}

/**
 * A stub value for a required prop, from its doc type: a string is the prop's
 * name, a number 0, a boolean false, a node a short text, a function a no-op,
 * a union of string literals its first one, an array empty.
 * @param {{name: string, type?: string}} prop
 * @returns {string} JavaScript source
 */
export function stubValue(prop) {
  const type = String(prop.type ?? '').trim();
  if (/=>/.test(type)) return 'noop';
  if (/^string$/.test(type)) return JSON.stringify(prop.name);
  if (/^number$/.test(type)) return '0';
  if (/^boolean$/.test(type)) return 'false';
  if (/^(?:React\.)?React(?:Node|Element)\b|^node$/i.test(type))
    return "'Sample'";
  const literal = /^'([^']*)'(?:\s*\|\s*'[^']*')*$/.exec(type);
  if (literal) return JSON.stringify(literal[1]);
  if (/\[\]$|^(?:ReadonlyArray|Array)</.test(type)) return '[]';
  return 'undefined';
}

/**
 * A sample stub for one Lab target: its copy rendered with each required
 * prop the doc's defaults leave out.
 * @param {string} key the target, `lab__<Name>`
 * @param {{name: string, type?: string}[]} props the required props
 * @returns {string} lines to insert in the samples object
 */
export function sampleStub(key, props) {
  const args = props
    .map(prop => `      ${JSON.stringify(prop.name)}: ${stubValue(prop)},`)
    .join('\n');
  return [
    `  ${STUB_NOTE}`,
    `  ${key}: ({C, React}) =>`,
    `    React.createElement(C, {`,
    args,
    `    }),`,
  ].join('\n');
}

/**
 * The samples source with each stub inserted above the marker line.
 * @param {string} source LAB_SAMPLES's text
 * @param {string[]} stubs
 */
export function insertStubs(source, stubs) {
  if (stubs.length === 0) return source;
  if (!source.includes(STUB_MARKER))
    throw new Error(
      `${LAB_SAMPLES} has no "${STUB_MARKER.trim()}" line to add samples above`,
    );
  return source.replace(STUB_MARKER, `${stubs.join('\n')}\n${STUB_MARKER}`);
}

/**
 * The Lab swizzle targets that need a sample, with their required props:
 * each Lab doc's component, as the swizzle proof names it (`lab__<file
 * name>`), whose doc names a required prop its defaults leave out, and that
 * has no sample and no mark.
 * @param {string} root
 * @param {{samples: object, needsNoSample: object, notRendered: object}} marks
 * @param {(doc: any, name: string) => string[]} requiredWithoutDefault
 * @returns {Promise<{key: string, props: {name: string, type?: string}[]}[]>}
 */
export async function unsampledTargets(root, marks, requiredWithoutDefault) {
  const src = path.join(root, 'packages/lab/src');
  const out = [];
  for (const file of docFiles(src, true)) {
    const name = path.basename(file, '.doc.mjs');
    const key = `lab__${name}`;
    if (
      marks.samples[key] ||
      marks.needsNoSample[key] ||
      marks.notRendered[key]
    )
      continue;
    const doc = await loadDoc(path.join(src, file)).catch(() => null);
    if (!doc) continue;
    const missing = requiredWithoutDefault(doc, name);
    if (missing.length === 0) continue;
    const entry = doc?.components?.find(c => c?.name === name) ?? doc;
    const props = missing.map(
      prop => (entry?.props ?? []).find(p => p?.name === prop) ?? {name: prop},
    );
    out.push({key, props});
  }
  return out;
}

/**
 * One sync pass over `root`.
 * @param {string} root
 * @param {{write: boolean}} options
 * @returns {Promise<{routes: string[], samples: string[]}>} what was missing
 */
export async function labSync(root, {write}) {
  const identity = await import(
    pathToFileURL(path.join(ROOT, 'apps/docsite/src/lib/shadcnRegistry.mjs'))
      .href
  );
  const {requiredWithoutDefault} = await import(
    pathToFileURL(path.join(ROOT, 'packages/cli/test/swizzle-proof/proof.mjs'))
      .href
  );
  const lockFile = path.join(root, ROUTE_LOCK);
  const lockText = fs.readFileSync(lockFile, 'utf8');
  const {text, missing: routes} = syncRouteLock(
    lockText,
    await labRouteEntries(root, identity),
  );
  const samplesFile = path.join(root, LAB_SAMPLES);
  const lab = await import(
    `${pathToFileURL(samplesFile).href}?read=${(reads += 1)}`
  );
  const shared = await import(
    pathToFileURL(
      path.join(ROOT, 'packages/cli/test/swizzle-proof/samples.mjs'),
    ).href
  );
  const targets = await unsampledTargets(
    root,
    {
      samples: {...lab.labSamples},
      needsNoSample: {...lab.labNeedsNoSample},
      notRendered: shared.notRendered,
    },
    requiredWithoutDefault,
  );
  if (write) {
    if (routes.length) fs.writeFileSync(lockFile, text);
    if (targets.length)
      fs.writeFileSync(
        samplesFile,
        insertStubs(
          fs.readFileSync(samplesFile, 'utf8'),
          targets.map(t => sampleStub(t.key, t.props)),
        ),
      );
  }
  return {routes, samples: targets.map(t => t.key)};
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const check = process.argv.includes('--check');
  const root = process.env.LAB_SYNC_ROOT ?? ROOT;
  labSync(root, {write: !check})
    .then(({routes, samples}) => {
      if (routes.length === 0 && samples.length === 0) {
        console.log(
          'lab:sync: every Lab route-lock entry and swizzle sample is present.',
        );
        return;
      }
      const lines = [
        ...routes.map(name => `  route-lock entry ${name} (${ROUTE_LOCK})`),
        ...samples.map(key => `  swizzle sample ${key} (${LAB_SAMPLES})`),
      ];
      if (check) {
        console.error(
          `lab:sync --check: missing:\n${lines.join('\n')}\nRun \`pnpm lab:sync\` and commit the result.`,
        );
        process.exitCode = 1;
      } else {
        console.log(
          `lab:sync: wrote:\n${lines.join('\n')}\nReview the stubs (marked "${STUB_NOTE}").`,
        );
      }
    })
    .catch(error => {
      console.error(error.message);
      process.exitCode = 1;
    });
}
