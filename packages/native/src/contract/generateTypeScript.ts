/**
 * @file contract/generateTypeScript.ts
 * @input Component contracts
 * @output Declaration files: core.d.ts, one per native platform, and shared.d.ts
 * @position Produces the platform-scoped types (AST-082 FR5, FR6). The package
 *   exports map selects one file per type-resolution condition
 */

import {BUILTIN_ICON_NAMES} from '../icons/defaults.js';
import {NATIVE_PLATFORMS, type NativePlatform} from '../platforms.js';
import type {ComponentContract, PropMap, PropSpec, PropType} from './types.js';

const HEADER = '// Generated by @astryxdesign/native. Do not edit.\n';

/**
 * `content` names the type of one child component: the open
 * `AstryxContentNode` in core contracts, a platform's `AstryxNode` in its wire.
 */
function tsType(type: PropType, content = 'AstryxContentNode'): string {
  switch (type.kind) {
    case 'string':
    case 'number':
    case 'boolean':
      return type.kind;
    case 'enum':
      return type.values.map(value => `'${value}'`).join(' | ');
    case 'numberEnum':
      return type.values.join(' | ');
    case 'array': {
      const inner = tsType(type.of, content);
      return `ReadonlyArray<${inner}>`;
    }
    case 'record':
      return `{${members(type.fields, ' ', content)}}`;
    case 'fn':
      return `(${type.args.map((arg, i) => `arg${i}: ${tsType(arg, content)}`).join(', ')}) => void`;
    case 'content':
      return `ReadonlyArray<${content}>`;
    case 'icon':
      return 'IconName';
    case 'textOrBoolean':
      return 'string | boolean';
    case 'named':
      return type.name;
  }
}

function key(name: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : `'${name}'`;
}

function members(
  props: PropMap,
  separator = '\n  ',
  content = 'AstryxContentNode',
): string {
  return Object.entries(props)
    .map(
      ([name, spec]) =>
        `${key(name)}${spec.optional ? '?' : ''}: ${tsType(spec.type, content)};`,
    )
    .join(separator);
}

function coreFile(contracts: readonly ComponentContract[]): string {
  const types = new Map<string, PropMap>();
  for (const contract of contracts) {
    for (const [name, fields] of Object.entries(contract.types)) {
      types.set(name, fields);
    }
  }
  const typeDecls = [...types].map(
    ([name, fields]) => `export interface ${name} {\n  ${members(fields)}\n}`,
  );
  const props = contracts.map(
    contract =>
      `/** Core contract. Base props attach to the ${contract.baseTarget}. */\n` +
      `export interface ${contract.name}CoreProps extends AstryxSharedBaseProps {\n  ${members(contract.core)}\n}`,
  );
  return (
    HEADER +
    '/** Base props shared by every platform (AST-082 FR7). */\n' +
    'export interface AstryxSharedBaseProps {\n  id?: string;\n  isHidden?: boolean;\n}\n' +
    '/** One child Astryx component in a content slot (AST-082 FR4). */\n' +
    'export interface AstryxContentNode {\n  readonly component: string;\n  readonly key: string;\n}\n' +
    '/** A shared icon name (AST-082 FR17): a built-in name or a registered `<library>:<name>`. */\n' +
    `export type IconName = ${BUILTIN_ICON_NAMES.map(name => `'${name}'`).join(' | ')} | \`\${string}:\${string}\`;\n` +
    [...typeDecls, ...props].join('\n') +
    '\n'
  );
}

function reExports(contracts: readonly ComponentContract[]): string {
  const names = new Set<string>([
    'AstryxSharedBaseProps',
    'AstryxContentNode',
    'IconName',
  ]);
  for (const contract of contracts) {
    Object.keys(contract.types).forEach(name => names.add(name));
    names.add(`${contract.name}CoreProps`);
  }
  return `export type {${[...names].join(', ')}} from './core.js';\n`;
}

/**
 * The wire a TypeScript core sends a native host (arm C): each component as
 * JSON with its data props, the callbacks it listens to, and the actions a
 * host sends back when a view calls one.
 */
function wire(
  contracts: readonly ComponentContract[],
  platform: NativePlatform | null,
): string {
  const nodes: string[] = [];
  const actions: string[] = [];
  for (const contract of contracts) {
    const props = {
      ...contract.core,
      ...(platform ? (contract.platforms[platform] ?? {}) : {}),
    };
    const data: Record<string, PropSpec> = {};
    const events: string[] = [];
    for (const [name, spec] of Object.entries(props)) {
      if (spec.type.kind === 'fn') {
        events.push(name);
        actions.push(
          `  | {key: string; component: '${contract.name}'; event: '${name}'; args: [${spec.type.args.map(arg => tsType(arg, 'AstryxNode')).join(', ')}]}`,
        );
      } else {
        data[name] = spec;
      }
    }
    nodes.push(
      `/** ${contract.name} as JSON from a TypeScript core. */\n` +
        `export interface ${contract.name}Node {\n` +
        `  component: '${contract.name}';\n` +
        '  key: string;\n' +
        '  base?: AstryxSharedBaseProps;\n' +
        `  props: {${members(data, ' ', 'AstryxNode')}};\n` +
        (events.length > 0
          ? `  /** The callbacks the core listens to. */\n  events?: ReadonlyArray<${events.map(e => `'${e}'`).join(' | ')}>;\n`
          : '') +
        '}',
    );
  }
  return [
    ...nodes,
    '/** Any Astryx component a TypeScript core can send. */',
    `export type AstryxNode = ${contracts.map(c => `${c.name}Node`).join(' | ')};`,
    '/** A callback a native view called, sent back to the core. */',
    `export type AstryxAction =\n${actions.join('\n') || '  never'};`,
  ].join('\n');
}

function platformFile(
  contracts: readonly ComponentContract[],
  platform: NativePlatform | null,
): string {
  const named = contracts.flatMap(c => Object.keys(c.types));
  const imports = `import type {${['AstryxSharedBaseProps', 'IconName', ...new Set(named), ...contracts.map(c => `${c.name}CoreProps`)].join(', ')}} from './core.js';\n`;
  const components = contracts.map(contract => {
    const extra = platform ? (contract.platforms[platform] ?? {}) : {};
    const body = Object.keys(extra).length > 0 ? `\n  ${members(extra)}\n` : '';
    const scope = platform
      ? `core contract plus the ${platform} contract`
      : 'core contract only';
    return (
      `/** ${contract.name} props: ${scope}. */\n` +
      `export interface ${contract.name}Props extends ${contract.name}CoreProps {${body}}\n` +
      `export declare function ${contract.name}(props: ${contract.name}Props): unknown;`
    );
  });
  return (
    HEADER +
    imports +
    reExports(contracts) +
    components.join('\n') +
    '\n' +
    wire(contracts, platform) +
    '\n'
  );
}

/** Returns file name to contents, relative to the types output folder. */
export function generateTypeScript(
  contracts: readonly ComponentContract[],
): Record<string, string> {
  const files: Record<string, string> = {
    'core.d.ts': coreFile(contracts),
    'shared.d.ts': platformFile(contracts, null),
  };
  for (const platform of NATIVE_PLATFORMS) {
    files[`${platform}.d.ts`] = platformFile(contracts, platform);
  }
  return files;
}
