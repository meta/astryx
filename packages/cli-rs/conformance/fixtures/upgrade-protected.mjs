// An app whose files are protected by ignore files, .gitattributes, generated
// headers and a symbolic link, with legacy source in each.
import * as fs from 'node:fs';
import * as path from 'node:path';

const LEGACY = "import {XDSSelector} from '@xds/core';\nexport const A = () => <XDSSelector items={[]} />;\n";

export default function (dir, {makeApp, writeFile}) {
  makeApp(dir, {name: 'protected-app'});
  const w = (rel, text) => writeFile(path.join(dir, rel), text);
  w('.gitignore', 'src/ignored/\n!src/ignored/keep.tsx\n');
  w('.gitattributes', 'src/gen/** linguist-generated=true\nsrc/vendor/** linguist-vendored\nsrc/gen/hand.tsx linguist-generated=false\n');
  w('src/App.tsx', LEGACY);
  w('src/ignored/skip.tsx', LEGACY);
  w('src/ignored/keep.tsx', LEGACY);
  w('src/gen/panel.tsx', LEGACY);
  w('src/gen/hand.tsx', LEGACY);
  w('src/vendor/lib.tsx', LEGACY);
  w('src/vendor/bundle.js', 'export const x = <<<;\n');
  w('src/header.tsx', `// @generated by a tool\n// Command: pnpm run gen:header\n${LEGACY}`);
  w('shared/linked.tsx', LEGACY);
  fs.symlinkSync('../shared/linked.tsx', path.join(dir, 'src/linked.tsx'));
}
