//! The app's theme record: the generated theme module.
//! Port of foundation/config/theme-state.mjs.

use crate::commands::template::fsutil;
use crate::json::{Map, Value};
use std::path::Path;

pub const THEME_MODULE_BASENAME: &str = "astryx-themes";
pub const THEME_MODULE_MARKER: &str = "@generated by `astryx theme` — do not edit manually.";
pub const THEME_RECORD_MARKER: &str = "@astryx-theme-record";

#[derive(Debug, Clone)]
pub struct StateError(pub String);

pub fn is_slug(s: &str) -> bool {
    // /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/u
    let mut chars = s.chars();
    match chars.next() {
        Some(c) if c.is_ascii_lowercase() => {}
        _ => return false,
    }
    let parts: Vec<&str> = s.split('-').collect();
    parts.iter().all(|p| !p.is_empty() && p.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit()))
}

fn fmt_cmd(cmd: &str) -> String {
    crate::cli::env::format_cli_command(cmd)
}

/// `findThemeProject`.
pub fn find_theme_project(cwd: &str) -> Result<(String, String), StateError> {
    let mut dir = fsutil::normalize(cwd);
    for _ in 0..50 {
        let pf = fsutil::join(&dir, "package.json");
        if Path::new(&pf).exists() {
            return Ok((dir, pf));
        }
        let p = fsutil::dirname(&dir);
        if p == dir {
            break;
        }
        dir = p;
    }
    Err(StateError("No package.json found. Run this command inside an app project.".into()))
}

pub fn is_local_owner(owner: &str) -> bool {
    owner.starts_with("./") || owner.starts_with("../") || owner.starts_with('/')
}

fn uses_typescript(project_dir: &str) -> bool {
    let Ok(rd) = std::fs::read_dir(project_dir) else { return false };
    rd.filter_map(|e| e.ok()).any(|e| {
        let n = e.file_name().to_string_lossy().into_owned();
        e.file_type().map(|t| t.is_file()).unwrap_or(false)
            && n.starts_with("tsconfig")
            && n.ends_with(".json")
            && {
                // /^tsconfig(?:\.[^.]+)*\.json$/
                let mid = &n["tsconfig".len()..n.len() - ".json".len()];
                mid.is_empty() || (mid.starts_with('.') && mid[1..].split('.').all(|p| !p.is_empty()))
            }
    })
}

pub fn module_candidates(project_dir: &str) -> Vec<String> {
    let src = fsutil::join(project_dir, "src");
    let has_src = Path::new(&src).is_dir();
    let ts = uses_typescript(project_dir);
    let (pd, od) = if has_src { (src.clone(), project_dir.to_string()) } else { (project_dir.to_string(), src.clone()) };
    let (pe, oe) = if ts { (".ts", ".js") } else { (".js", ".ts") };
    vec![
        fsutil::join(&pd, &format!("{THEME_MODULE_BASENAME}{pe}")),
        fsutil::join(&pd, &format!("{THEME_MODULE_BASENAME}{oe}")),
        fsutil::join(&od, &format!("{THEME_MODULE_BASENAME}{pe}")),
        fsutil::join(&od, &format!("{THEME_MODULE_BASENAME}{oe}")),
    ]
}

#[derive(Debug, Clone)]
pub struct ThemeModule {
    pub file: String,
    pub path: String,
    pub typescript: bool,
    pub expected_original: Option<Vec<u8>>,
    pub exists: bool,
}

pub fn resolve_module(project_dir: &str, for_write: bool) -> Result<ThemeModule, StateError> {
    let cands = module_candidates(project_dir);
    let generated: Vec<&String> = cands
        .iter()
        .filter(|f| std::fs::read(f).map(|b| String::from_utf8_lossy(&b).contains(THEME_MODULE_MARKER)).unwrap_or(false))
        .collect();
    if generated.len() > 1 {
        return Err(StateError(format!(
            "More than one generated theme module exists: {}. Keep one and remove the others before running the command again.",
            generated.iter().map(|f| fsutil::relative(project_dir, f)).collect::<Vec<_>>().join(", ")
        )));
    }
    let file = generated.first().map(|s| s.to_string()).unwrap_or_else(|| cands[0].clone());
    if for_write {
        if let Err(e) = fsutil::assert_within(&fsutil::relative(project_dir, &file), project_dir, "generated theme module") {
            return Err(StateError(e.message));
        }
    }
    let mut expected = None;
    if Path::new(&file).exists() {
        let bytes = std::fs::read(&file).unwrap_or_default();
        if !String::from_utf8_lossy(&bytes).contains(THEME_MODULE_MARKER) {
            if for_write {
                return Err(StateError(format!(
                    "Refusing to replace {}: it is not an Astryx-generated theme module. Move that file before adding themes.",
                    fsutil::relative(project_dir, &file)
                )));
            }
        } else {
            expected = Some(bytes);
        }
    }
    Ok(ThemeModule {
        path: fsutil::relative(project_dir, &file),
        typescript: file.ends_with(".ts"),
        file,
        expected_original: expected,
        exists: generated.len() == 1,
    })
}

#[derive(Debug, Clone)]
pub struct ThemeState {
    pub project_dir: String,
    pub package_file: String,
    /// slug -> owner, in record order.
    pub themes: indexmap::IndexMap<String, String>,
    pub default_slug: Option<String>,
    pub configured: bool,
    pub module: ThemeModule,
}

fn parse_record(source: &str, label: &str) -> Result<(indexmap::IndexMap<String, String>, String), StateError> {
    if !source.contains(THEME_MODULE_MARKER) {
        return Err(StateError(format!("{label} does not carry the Astryx generated marker.")));
    }
    let re = regress::Regex::new(r"^\s*\*\s*@astryx-theme-record\s+").unwrap();
    let lines: Vec<&str> = source.split('\n').map(|l| l.strip_suffix('\r').unwrap_or(l)).filter(|l| re.find(l).is_some()).collect();
    if lines.len() != 1 {
        return Err(StateError(format!(
            "{label} must carry exactly one static {THEME_RECORD_MARKER} header. Regenerate it with `{}`.",
            fmt_cmd("theme add <slug>")
        )));
    }
    let m = re.find(lines[0]).unwrap();
    let payload = &lines[0][m.end()..];
    let record: Value = crate::commands::theme_build::jsonparse::parse(payload)
        .map_err(|e| StateError(format!("{label} has an invalid {THEME_RECORD_MARKER} header: {e}")))?;
    let bad_shape = || {
        StateError(format!(
            "{label} must carry a static {THEME_RECORD_MARKER} header. Regenerate it with `{}`.",
            fmt_cmd("theme add <slug>")
        ))
    };
    let obj = record.as_object().ok_or_else(bad_shape)?;
    let themes = obj.get("themes").and_then(|t| t.as_object()).ok_or_else(bad_shape)?;
    if obj.len() != 2 || !obj.contains_key("defaultThemeSlug") {
        return Err(StateError(format!(
            "{label} {THEME_RECORD_MARKER} header must contain only themes and defaultThemeSlug."
        )));
    }
    let mut out = indexmap::IndexMap::new();
    for (slug, owner) in js_entries(themes) {
        match owner.as_str() {
            Some(o) if is_slug(&slug) && !o.trim().is_empty() => {
                out.insert(slug, o.to_string());
            }
            _ => {
                return Err(StateError(format!(
                    "{label} theme record must map lowercase kebab-case slugs to package names or local theme roots."
                )))
            }
        }
    }
    match obj.get("defaultThemeSlug").and_then(|v| v.as_str()) {
        Some(d) if is_slug(d) => Ok((out, d.to_string())),
        _ => Err(StateError(format!(
            "{label} defaultThemeSlug must be a lowercase kebab-case slug. Regenerate it with `{}`.",
            fmt_cmd("theme use <slug>")
        ))),
    }
}

/// Object entries in JS order (integer-like keys first).
fn js_entries(m: &Map<String, Value>) -> Vec<(String, Value)> {
    let ordered = crate::json::js_key_order(m.clone());
    ordered.into_iter().collect()
}

/// `readThemeState`.
pub fn read(cwd: &str) -> Result<ThemeState, StateError> {
    let (project_dir, package_file) = find_theme_project(cwd)?;
    let module = resolve_module(&project_dir, false)?;
    if module.exists {
        if let Some(bytes) = &module.expected_original {
            let (themes, default) = parse_record(&String::from_utf8_lossy(bytes), &module.path)?;
            return Ok(ThemeState { project_dir, package_file, themes, default_slug: Some(default), configured: true, module });
        }
    }
    Ok(ThemeState {
        project_dir,
        package_file,
        themes: indexmap::IndexMap::new(),
        default_slug: None,
        configured: false,
        module,
    })
}

/// One resolved theme entry for the generated module.
#[derive(Debug, Clone)]
pub struct Entry {
    pub slug: String,
    pub owner: String,
    pub export_name: String,
    pub module: String,
    pub stylesheet: String,
    pub font_stylesheet: Option<String>,
    pub source: String,
    pub module_file: Option<String>,
    pub stylesheet_file: Option<String>,
    pub font_stylesheet_file: Option<String>,
}

fn json_str(s: &str) -> String {
    let mut o = String::new();
    crate::json::quote(&mut o, s);
    o
}

/// `renderThemeModule`.
pub fn render_module(themes: &[Entry], default_slug: &str, typescript: bool) -> Result<String, StateError> {
    if !themes.iter().any(|t| t.slug == default_slug) {
        return Err(StateError(format!(
            "Default theme \"{default_slug}\" is not added. Run `{}` first.",
            fmt_cmd(&format!("theme add {default_slug}"))
        )));
    }
    let mut imports = Vec::new();
    let mut entries = Vec::new();
    let mut owners = String::from("{");
    for (i, t) in themes.iter().enumerate() {
        let local = format!("_astryxTheme{i}");
        imports.push(format!("import {{{} as {local}}} from {};", t.export_name, json_str(&t.module)));
        imports.push(format!("import {};", json_str(&t.stylesheet)));
        if let Some(f) = &t.font_stylesheet {
            imports.push(format!("import {};", json_str(f)));
        }
        entries.push(format!("  {}: {local},", json_str(&t.slug)));
        if i > 0 {
            owners.push(',');
        }
        owners.push_str(&format!("{}:{}", json_str(&t.slug), json_str(&t.owner)));
    }
    owners.push('}');
    let record = format!("{{\"themes\":{owners},\"defaultThemeSlug\":{}}}", json_str(default_slug));
    Ok(format!(
        "/**\n * {THEME_MODULE_MARKER}\n * {THEME_RECORD_MARKER} {record}\n */\n\n{}\n\nexport const themes = {{\n{}\n}}{};\n{}\nexport const defaultThemeSlug{} = {};\n",
        imports.join("\n"),
        entries.join("\n"),
        if typescript { " as const" } else { "" },
        if typescript { "export type ThemeSlug = keyof typeof themes;\n" } else { "" },
        if typescript { ": keyof typeof themes" } else { "" },
        json_str(default_slug)
    ))
}

/// `localImportSpecifier`.
pub fn local_import_specifier(module_file: &str, target: &str) -> String {
    let rel = fsutil::relative(&fsutil::dirname(module_file), target);
    if rel.starts_with('.') { rel } else { format!("./{rel}") }
}
