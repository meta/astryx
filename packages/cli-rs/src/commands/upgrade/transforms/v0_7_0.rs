const CORE_IMPORT_RE: &str = "^@(astryxdesign|xds)\\/core(?:\\/|$)";

fn ext_of(path: &str) -> &str {
    let base = path.rsplit('/').next().unwrap_or(path);
    match base.rfind('.') {
        Some(i) if i > 0 => &base[i..],
        _ => "",
    }
}

pub fn validate_data_token_ownership(source: &str, path: &str, _o: &Value) -> TResult {
    if ext_of(path) == ".css" && source.contains("@generated by `astryx theme build`") && jsre::test(":root\\s*\\{[^}]*--color-data-", "su", source) {
        return Err(CodemodError::regenerate("This generated theme CSS still emits canonical data defaults at :root. Rebuild it with `astryx theme build`; defaults come from @astryxdesign/core/astryx.css in prebuilt mode, and in a source build from the @astryxdesign/build PostCSS integration or dataVars imports.", vec!["astryx theme build".to_string()]));
    }
    Ok(None)
}

const CONTROL_COMPONENTS: &[&str] = &["TextInput", "TextArea", "NumberInput", "FileInput", "DateInput", "DateRangeInput", "DateTimeInput", "TimeInput", "Selector", "MultiSelector", "ComplexSelector"];
const CONTAINER_COMPONENTS: &[&str] = &["Typeahead", "Tokenizer", "CheckboxList", "RadioList", "Slider"];
const FIELD_TODO: &str = " TODO(astryx upgrade): root styling is no longer accepted here; merge it into ";

pub fn migrate_field_input_styling(source: &str, path: &str, _o: &Value) -> TResult {
    if !jsre::test("xstyle|className|style", "u", source) {
        return Ok(None);
    }
    if !CONTROL_COMPONENTS.iter().chain(CONTAINER_COMPONENTS).any(|n| source.contains(n)) {
        return Ok(None);
    }
    let mut j = parse_file(source, path)?;
    let pkg = "^@(astryxdesign|xds)\\/core(\\/[A-Za-z]+)?$";
    let matches_import = |s: &str| jsre::test(pkg, "u", s);
    let mut input_groups: Vec<String> = vec![];
    let mut namespaces: Vec<String> = vec![];
    for ip in j.find("ImportDeclaration") {
        if j.ast.str_of(ip.node, "importKind") == Some("type") {
            continue;
        }
        match source_value(&j, ip.node) {
            Some(s) if matches_import(&s) => {}
            _ => continue,
        }
        for s in j.ast.list(ip.node, "specifiers") {
            if j.ast.str_of(s, "importKind") == Some("type") {
                continue;
            }
            if j.ast.is(s, "ImportSpecifier") && imported_name(&j, s).as_deref() == Some("InputGroup") {
                input_groups.push(local_name(&j, s).unwrap_or("InputGroup".into()));
            } else if j.ast.is(s, "ImportNamespaceSpecifier") {
                namespaces.push(local_name(&j, s).unwrap_or_default());
            }
        }
    }
    let style_props: &[&str] = &["xstyle", "className", "style"];
    let comps: Vec<(&str, &[&str])> = CONTROL_COMPONENTS.iter().chain(CONTAINER_COMPONENTS).map(|c| (*c, style_props)).collect();
    let norm = |s: &str| s.to_string();
    let o = PropOptions { matches_import: &matches_import, components: &comps, normalize: &norm };
    let mut changed = false;
    transform_prop_paths(&mut j, &o, &mut |j, op, attr, comp, _| {
        let mut part = if CONTROL_COMPONENTS.contains(&comp) { "control" } else { "container" };
        if part == "container" && comp == "Typeahead" {
            let mut inside = false;
            let mut p = op.parent_path().and_then(|pp| pp.parent_path());
            while let Some(pp) = p {
                if j.ast.is(pp.node, "JSXElement") {
                    let oe = j.ast.child(pp.node, "openingElement").unwrap();
                    let name = j.ast.child(oe, "name").unwrap();
                    let local = if j.ast.is(name, "JSXIdentifier") && input_groups.iter().any(|g| Some(g.as_str()) == j.ast.name(name)) {
                        j.ast.name(name).map(|s| s.to_string())
                    } else if j.ast.is(name, "JSXMemberExpression") {
                        let ob = j.ast.child(name, "object");
                        let pr = j.ast.child(name, "property");
                        match (ob, pr) {
                            (Some(ob), Some(pr)) if j.ast.is(ob, "JSXIdentifier") && j.ast.is(pr, "JSXIdentifier") && j.ast.name(pr) == Some("InputGroup") && namespaces.iter().any(|n| Some(n.as_str()) == j.ast.name(ob)) => j.ast.name(ob).map(|s| s.to_string()),
                            _ => None,
                        }
                    } else {
                        None
                    };
                    if let Some(l) = local {
                        if j.is_module_binding(&pp, &l) {
                            inside = true;
                            break;
                        }
                    }
                }
                p = pp.parent_path();
            }
            if inside {
                part = "control";
            }
        }
        let name = attr_name(j, attr).unwrap_or_default();
        let suffix = match name.as_str() {
            "xstyle" => "Xstyle",
            "className" => "ClassName",
            _ => "Style",
        };
        let next = format!("{}{}", part, suffix);
        if find_attr(j, op.node, &next).is_some() {
            let text = format!("{}`{}`. ", FIELD_TODO, next);
            let mut cs = comments_of(j, attr).unwrap_or_default();
            if !cs.iter().any(|&c| j.ast.str_of(c, "value") == Some(text.as_str())) {
                let c = comment(j, true, &text, true, false);
                cs.push(c);
                changed = true;
            }
            set_comments(j, attr, cs);
            return;
        }
        let id = j.jsx_identifier(&next);
        j.ast.set_node(attr, "name", id);
        changed = true;
    });
    done(&j, changed)
}

const SHEET_TODO: &str = " TODO(astryx upgrade): BottomSheet now pads its content like Dialog. padding={0} keeps the unpadded content box, but it also removes the inset between a nested Layout's regions, which the Layout's own padding does not restore. Drop padding={0} and the sheet content's own inset, or give the Layout its inset another way. ";

struct Bindings {
    direct: Vec<String>,
    namespaces: Vec<String>,
}

fn find_bindings(j: &J, component: &str) -> Bindings {
    let mut b = Bindings { direct: vec![], namespaces: vec![] };
    for ip in j.find("ImportDeclaration") {
        if j.ast.str_of(ip.node, "importKind") == Some("type") {
            continue;
        }
        let src = match source_value(j, ip.node) {
            Some(s) if jsre::test(CORE_IMPORT_RE, "", &s) => s,
            _ => continue,
        };
        let subpath = src.rsplit('/').next().unwrap_or("").to_string();
        for s in j.ast.list(ip.node, "specifiers") {
            if j.ast.str_of(s, "importKind") == Some("type") {
                continue;
            }
            match j.ast.ty(s) {
                "ImportSpecifier" => {
                    let imp = j.ast.child(s, "imported").and_then(|i| j.ast.name(i).or_else(|| j.ast.str_of(i, "value")).map(|x| x.to_string()));
                    if imp.as_deref() == Some(component) {
                        b.direct.push(local_name(j, s).unwrap_or(component.to_string()));
                    }
                }
                "ImportDefaultSpecifier" if subpath == component => b.direct.push(local_name(j, s).unwrap_or_default()),
                "ImportNamespaceSpecifier" => b.namespaces.push(local_name(j, s).unwrap_or_default()),
                _ => {}
            }
        }
    }
    b
}

fn name_matches(j: &J, name: usize, b: &Bindings, component: &str) -> bool {
    if j.ast.is(name, "JSXIdentifier") {
        return b.direct.iter().any(|d| Some(d.as_str()) == j.ast.name(name));
    }
    if !j.ast.is(name, "JSXMemberExpression") {
        return false;
    }
    let ob = j.ast.child(name, "object");
    let pr = j.ast.child(name, "property");
    match ob {
        Some(ob) if j.ast.is(ob, "JSXIdentifier") && b.namespaces.iter().any(|n| Some(n.as_str()) == j.ast.name(ob)) => pr.and_then(|p| j.ast.str_of(p, "name")) == Some(component),
        _ => false,
    }
}

fn jsx_module_binding(j: &J, p: &NPath, name: usize) -> bool {
    let local = if j.ast.is(name, "JSXIdentifier") {
        j.ast.name(name)
    } else if j.ast.is(name, "JSXMemberExpression") {
        j.ast.child(name, "object").filter(|o| j.ast.is(*o, "JSXIdentifier")).and_then(|o| j.ast.name(o))
    } else {
        None
    };
    match local {
        Some(l) => j.is_module_binding(p, l),
        None => false,
    }
}

fn meaningful_children(j: &J, el: usize) -> Vec<usize> {
    j.ast
        .list(el, "children")
        .into_iter()
        .filter(|&c| match j.ast.ty(c) {
            "JSXText" => !js_trim(j.ast.str_of(c, "value").unwrap_or("")).is_empty(),
            "JSXExpressionContainer" => !j.ast.child(c, "expression").map(|e| j.ast.is(e, "JSXEmptyExpression")).unwrap_or(false),
            _ => true,
        })
        .collect()
}

pub fn preserve_bottom_sheet_padding(source: &str, path: &str, _o: &Value) -> TResult {
    if !source.contains("BottomSheet") {
        return Ok(None);
    }
    let mut j = parse_file(source, path)?;
    let sheets = find_bindings(&j, "BottomSheet");
    if sheets.direct.is_empty() && sheets.namespaces.is_empty() {
        return Ok(None);
    }
    let sections = find_bindings(&j, "Section");
    let layouts = find_bindings(&j, "Layout");
    let mut changed = false;
    for ep in j.find("JSXElement") {
        let opening = j.ast.child(ep.node, "openingElement").unwrap();
        let oname = j.ast.child(opening, "name").unwrap();
        if !name_matches(&j, oname, &sheets, "BottomSheet") || !jsx_module_binding(&j, &ep, oname) {
            continue;
        }
        let mut attrs = j.ast.list(opening, "attributes");
        if attrs.iter().any(|&a| attr_name(&j, a).as_deref() == Some("padding")) {
            continue;
        }
        let kids = meaningful_children(&j, ep.node);
        let has_children_attr = attrs.iter().any(|&a| attr_name(&j, a).as_deref() == Some("children"));
        if !has_children_attr && kids.len() == 1 && j.ast.is(kids[0], "JSXElement") {
            let ko = j.ast.child(kids[0], "openingElement").unwrap();
            let kn = j.ast.child(ko, "name").unwrap();
            let raw0 = j.ast.list(ep.node, "children")[0];
            let kp = ep.child("children", raw0, true);
            if (name_matches(&j, kn, &sections, "Section") || name_matches(&j, kn, &layouts, "Layout")) && jsx_module_binding(&j, &kp, kn) {
                continue;
            }
        }
        let zero = j.numeric_literal(0.0);
        let c = j.jsx_expression_container(zero);
        let pad = j.jsx_attribute("padding", Some(c));
        match attrs.iter().position(|&a| j.ast.is(a, "JSXSpreadAttribute")) {
            None => attrs.push(pad),
            Some(i) => attrs.insert(i, pad),
        }
        j.ast.set_list(opening, "attributes", attrs);
        changed = true;
        let nested = j.find_in(&ep, "JSXOpeningElement").into_iter().any(|op| {
            let n = j.ast.child(op.node, "name").unwrap();
            name_matches(&j, n, &layouts, "Layout") && jsx_module_binding(&j, &op, n)
        });
        if nested {
            let mut p = Some(ep.clone());
            while let Some(pp) = &p {
                if type_matches(j.ast.ty(pp.node), "Statement") {
                    break;
                }
                p = pp.parent_path();
            }
            if let Some(pp) = p {
                let host = pp.node;
                let mut cs = comments_of(&j, host).unwrap_or_default();
                if !cs.iter().any(|&c| j.ast.str_of(c, "value") == Some(SHEET_TODO)) {
                    let c = comment(&mut j, true, SHEET_TODO, true, false);
                    cs.push(c);
                }
                set_comments(&mut j, host, cs);
            }
        }
    }
    Ok(if changed { Some(j.to_source(None)) } else { None })
}

const OLD_NAME: &str = "emptySearchResultsText";
const NEW_NAME: &str = "emptySearchText";
const BOTH_SET_COMMENT: &str = " TODO(astryx upgrade): emptySearchResultsText was removed and emptySearchText is already set here; delete the old one if the new value is what you want. ";
const UNREADABLE_OBJECT_COMMENT: &str = " TODO(astryx upgrade): emptySearchResultsText was removed. Rename it to emptySearchText by hand; this object has a spread or computed key. ";
const SPREAD_COMMENT: &str = " TODO(astryx upgrade): emptySearchResultsText was removed. This element spreads props that may carry either name; rename to emptySearchText where the props are built and delete the old one. ";
const OPAQUE_TRIGGERS_COMMENT: &str = " TODO(astryx upgrade): emptySearchResultsText was removed. These triggers are built elsewhere; rename the key to emptySearchText where they are built. ";

fn unwrap2(j: &J, n: Option<usize>) -> Option<usize> {
    let mut cur = n;
    while let Some(c) = cur {
        if matches!(j.ast.ty(c), "TSAsExpression" | "TSSatisfiesExpression" | "TSTypeAssertion" | "TSNonNullExpression" | "TypeCastExpression" | "ParenthesizedExpression") {
            cur = j.ast.child(c, "expression");
        } else {
            break;
        }
    }
    cur
}

fn static_string_name(j: &J, prop: usize) -> Option<String> {
    if j.ast.flag(prop, "computed") {
        return None;
    }
    let key = j.ast.child(prop, "key")?;
    match j.ast.ty(key) {
        "Identifier" => j.ast.name(key).map(|s| s.to_string()),
        "StringLiteral" | "Literal" => j.ast.str_of(key, "value").map(|s| s.to_string()),
        _ => None,
    }
}

fn add_comment(j: &mut J, node: usize, text: &str) -> bool {
    let mut cs = comments_of(j, node).unwrap_or_default();
    if cs.iter().any(|&c| j.ast.str_of(c, "value") == Some(text)) {
        set_comments(j, node, cs);
        return false;
    }
    let c = comment(j, true, text, true, false);
    cs.push(c);
    set_comments(j, node, cs);
    true
}

fn rename_trigger_key(j: &mut J, obj: usize) -> bool {
    let props = j.ast.list(obj, "properties");
    let old = props.iter().copied().find(|&p| static_string_name(j, p).as_deref() == Some(OLD_NAME));
    let unreadable = props.iter().copied().find(|&p| matches!(j.ast.ty(p), "SpreadElement" | "SpreadProperty") || j.ast.flag(p, "computed"));
    if let Some(u) = unreadable {
        return add_comment(j, old.unwrap_or(u), UNREADABLE_OBJECT_COMMENT);
    }
    let old = match old {
        Some(o) => o,
        None => return false,
    };
    if props.iter().any(|&p| static_string_name(j, p).as_deref() == Some(NEW_NAME)) {
        return add_comment(j, old, BOTH_SET_COMMENT);
    }
    let k = j.identifier(NEW_NAME);
    j.ast.set_node(old, "key", k);
    if j.ast.flag(old, "shorthand") {
        j.ast.set(old, "shorthand", V::Bool(false));
    }
    true
}

pub fn rename_empty_search_results_text(source: &str, path: &str, _o: &Value) -> TResult {
    let mut j = parse_file(source, path)?;
    let mut changed = false;
    let matches_import = |s: &str| jsre::test(CORE_IMPORT_RE, "", s);
    let norm = |s: &str| s.to_string();
    let comps: &[(&str, &[&str])] = &[("Tokenizer", &[OLD_NAME]), ("Typeahead", &[OLD_NAME]), ("BaseTypeahead", &[OLD_NAME]), ("ChatComposerInput", &["triggers"])];
    let o = PropOptions { matches_import: &matches_import, components: comps, normalize: &norm };
    transform_prop_paths(&mut j, &o, &mut |j, op, prop, comp, _| {
        let attrs = j.ast.list(op.node, "attributes");
        let has_spread = attrs.iter().any(|&a| j.ast.is(a, "JSXSpreadAttribute"));
        if comp == "ChatComposerInput" {
            let value = match j.ast.child(prop, "value") {
                Some(v) if j.ast.is(v, "JSXExpressionContainer") => unwrap2(j, j.ast.child(v, "expression")),
                _ => None,
            };
            let items: Vec<Option<usize>> = match value {
                Some(v) if j.ast.is(v, "ArrayExpression") => j.ast.list_opt(v, "elements").into_iter().map(|e| unwrap2(j, e)).collect(),
                v => vec![v],
            };
            let mut opaque = has_spread;
            for it in items {
                match it {
                    Some(o) if j.ast.is(o, "ObjectExpression") => changed = rename_trigger_key(j, o) || changed,
                    _ => opaque = true,
                }
            }
            if opaque {
                changed = add_comment(j, prop, OPAQUE_TRIGGERS_COMMENT) || changed;
            }
            return;
        }
        if has_spread {
            changed = add_comment(j, prop, SPREAD_COMMENT) || changed;
            return;
        }
        if attrs.iter().any(|&a| attr_name(j, a).as_deref() == Some(NEW_NAME)) {
            changed = add_comment(j, prop, BOTH_SET_COMMENT) || changed;
            return;
        }
        let n = j.ast.child(prop, "name").unwrap();
        j.set_name(n, NEW_NAME);
        changed = true;
    });
    for (component, props) in comps {
        let sentinel = format!("__astryx_spread_{}", component);
        let sent_props: &[&str] = &[sentinel.as_str()];
        let one: &[(&str, &[&str])] = &[(component, sent_props)];
        let o1 = PropOptions { matches_import: &matches_import, components: one, normalize: &norm };
        for op in j.find("JSXOpeningElement") {
            let attrs = j.ast.list(op.node, "attributes");
            if !attrs.iter().any(|&a| j.ast.is(a, "JSXSpreadAttribute")) {
                continue;
            }
            if attrs.iter().any(|&a| j.ast.is(a, "JSXAttribute") && attr_name(&j, a).map(|n| props.contains(&n.as_str())).unwrap_or(false)) {
                continue;
            }
            let imports = imported_components(&j, &o1);
            if imports.direct.is_empty() && imports.namespaces.is_empty() {
                continue;
            }
            let name = j.ast.child(op.node, "name").unwrap();
            if resolve_imported_component(&j, name, &op, &imports, &o1).is_none() {
                continue;
            }
            let spread = attrs.into_iter().find(|&a| j.ast.is(a, "JSXSpreadAttribute")).unwrap();
            let text = if *component == "ChatComposerInput" { OPAQUE_TRIGGERS_COMMENT } else { SPREAD_COMMENT };
            changed = add_comment(&mut j, spread, text) || changed;
        }
    }
    let _ = unwrap_ts;
    done(&j, changed)
}
