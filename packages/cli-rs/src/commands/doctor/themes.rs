//! The theme checks (port of `api/doctor/theme-checks.mjs`).

use super::env;
use super::{Check, Status};
use crate::discovery::nodepath as np;
use crate::json::Value;

const CHECKS: &[(&str, &str)] = &[
    ("theme-owners", "Theme owners and built imports"),
    ("theme-module", "Generated theme module"),
    ("theme-module-import", "App imports the theme module"),
    ("theme-stylesheet-imports", "Built theme stylesheet imports"),
    ("theme-local-builds", "Local theme build freshness"),
    ("theme-private-variables", "Private theme variables"),
    ("theme-core-peers", "Theme Core peer compatibility"),
    ("theme-default", "Default added theme"),
    ("theme-fonts", "Theme font loading"),
    ("theme-global-rules", "Cross-theme global CSS rules"),
];

const THEME_MODULE_MARKER: &str = "@generated by `astryx theme` \u{2014} do not edit manually.";

fn unavailable(message: &str, module_error: Option<&str>) -> Vec<Check> {
    CHECKS
        .iter()
        .map(|(id, label)| match module_error {
            Some(e) if *id == "theme-module" => Check::new(id, label, Status::Fail, e).fix(format!(
                "Keep one CLI-generated astryx-themes.ts or astryx-themes.js file, then run `{}`.",
                env::fmt0("theme add <slug>")
            )),
            _ => Check::new(id, label, Status::Info, message),
        })
        .collect()
}

pub struct ThemeState {
    pub project_dir: String,
    pub package_file: String,
    pub configured: bool,
    pub legacy_theme: Option<String>,
}

fn find_theme_project(cwd: &str) -> Option<(String, String)> {
    let mut dir = np::resolve1(cwd);
    for _ in 0..50 {
        let pf = np::join2(&dir, "package.json");
        if np::exists(&pf) {
            return Some((dir, pf));
        }
        let parent = np::dirname(&dir);
        if parent == dir {
            break;
        }
        dir = parent;
    }
    None
}

fn uses_typescript(dir: &str) -> bool {
    let Ok(rd) = std::fs::read_dir(dir) else { return false };
    rd.filter_map(|e| e.ok()).any(|e| {
        e.file_type().map(|t| t.is_file()).unwrap_or(false)
            && crate::doctor_re!(r"^tsconfig(?:\.[^.]+)*\.json$", "u").find(&e.file_name().to_string_lossy()).is_some()
    })
}

fn module_candidates(project_dir: &str) -> Vec<String> {
    let src = np::join2(project_dir, "src");
    let has_src = np::is_dir(&src);
    let ts = uses_typescript(project_dir);
    let (pref, other) = if has_src { (src.clone(), project_dir.to_string()) } else { (project_dir.to_string(), src.clone()) };
    let (pe, oe) = if ts { (".ts", ".js") } else { (".js", ".ts") };
    vec![
        np::join2(&pref, &format!("astryx-themes{pe}")),
        np::join2(&pref, &format!("astryx-themes{oe}")),
        np::join2(&other, &format!("astryx-themes{pe}")),
        np::join2(&other, &format!("astryx-themes{oe}")),
    ]
}

/// `resolveThemeModule(projectDir, {forWrite})`: Err carries the message.
fn resolve_theme_module(project_dir: &str, for_write: bool) -> Result<(String, bool), String> {
    let candidates = module_candidates(project_dir);
    let generated: Vec<&String> =
        candidates.iter().filter(|f| std::fs::read(f).map(|b| String::from_utf8_lossy(&b).contains(THEME_MODULE_MARKER)).unwrap_or(false)).collect();
    if generated.len() > 1 {
        return Err(format!(
            "More than one generated theme module exists: {}. Keep one and remove the others before running the command again.",
            generated.iter().map(|f| np::relative(project_dir, f)).collect::<Vec<_>>().join(", ")
        ));
    }
    let file = generated.first().map(|s| (*s).clone()).unwrap_or_else(|| candidates[0].clone());
    if np::exists(&file) && for_write {
        let text = std::fs::read(&file).map(|b| String::from_utf8_lossy(&b).into_owned()).unwrap_or_default();
        if !text.contains(THEME_MODULE_MARKER) {
            return Err(format!(
                "Refusing to replace {}: it is not an Astryx-generated theme module. Move that file before adding themes.",
                np::relative(project_dir, &file)
            ));
        }
    }
    Ok((file, generated.len() == 1))
}

/// `readThemeState(cwd)` as far as doctor branches on it.
pub fn read_theme_state(cwd: &str) -> Result<ThemeState, String> {
    let (project_dir, package_file) =
        find_theme_project(cwd).ok_or_else(|| "No package.json found. Run this command inside an app project.".to_string())?;
    let (_file, exists) = resolve_theme_module(&project_dir, false)?;
    let legacy = np::read_json(&package_file)
        .and_then(|p| p.get("astryx").and_then(|a| a.as_object()).and_then(|a| a.get("theme")).and_then(|t| t.as_str()).map(String::from));
    Ok(ThemeState { project_dir, package_file, configured: exists, legacy_theme: if exists { None } else { legacy } })
}

fn app_package_names_theme(cwd: &str) -> bool {
    let Ok(state) = read_theme_state(cwd) else { return false };
    np::read_json(&state.package_file)
        .and_then(|p| p.get("astryx").cloned())
        .map(|a| crate::discovery::paths::js_truthy(a.get("theme")))
        .unwrap_or(false)
}

/// `listDoctorThemePackages(cwd)`.
pub fn list_theme_packages(cwd: &str) -> Vec<String> {
    let mut dir = np::resolve1(cwd);
    let mut nm = None;
    for _ in 0..6 {
        let c = np::join2(&dir, "node_modules");
        if np::exists(&c) {
            nm = Some(c);
            break;
        }
        let parent = np::dirname(&dir);
        if parent == dir {
            break;
        }
        dir = parent;
    }
    let Some(nm) = nm else { return vec![] };
    let scope = np::join2(&nm, "@astryxdesign");
    let Some(entries) = crate::commands::doctor::support::read_dir_sorted(&scope) else { return vec![] };
    entries
        .into_iter()
        .filter(|e| e.name.starts_with("theme-"))
        .filter(|e| e.is_dir || (e.is_symlink && np::is_dir(&np::join2(&scope, &e.name))))
        .map(|e| format!("@astryxdesign/{}", e.name))
        .collect()
}

#[derive(Default)]
pub struct Wiring {
    pub wired: Vec<(String, String)>,
    pub unconfirmed: Vec<String>,
}

/// `themeImportWiring(cwd)`.
pub fn theme_import_wiring(cwd: &str) -> Wiring {
    super::themes_app::theme_import_wiring(cwd)
}

pub fn app_package_names_theme_pub(cwd: &str) -> bool {
    app_package_names_theme(cwd)
}

fn wired_list(wired: &[(String, String)]) -> String {
    let shown: Vec<String> = wired.iter().take(5).map(|(s, f)| format!("{s} ({f})")).collect();
    let more = wired.len() - shown.len();
    if more > 0 {
        format!("{} and {more} more", shown.join(", "))
    } else {
        shown.join(", ")
    }
}

/// `checkThemes(cwd, appChecks, wiring)`.
pub fn check_themes(cwd: &str, app: &[Check], wiring: &Wiring) -> Check {
    let label = "Theme packages";
    let managed = app.iter().any(|c| CHECKS.iter().any(|(id, _)| *id == c.id) && c.status != Status::Info);
    if managed {
        let needs: Vec<&Check> = app.iter().filter(|c| c.status == Status::Fail || c.status == Status::Warn).collect();
        let unproven: Vec<&Check> = app.iter().filter(|c| c.status == Status::Info).collect();
        if !needs.is_empty() {
            let ids = needs.iter().map(|c| c.id.clone()).collect::<Vec<_>>().join(", ");
            let one = needs.len() == 1;
            return Check::new(
                "themes",
                label,
                if needs.iter().any(|c| c.status == Status::Fail) { Status::Fail } else { Status::Warn },
                if one { format!("One theme check needs attention: {ids}.") } else { format!("{} theme checks need attention: {ids}.", needs.len()) },
            )
            .fix(if one { format!("Follow the fix on the {ids} check.") } else { format!("Follow the fix on each of these checks: {ids}.") });
        }
        if !unproven.is_empty() {
            let ids = unproven.iter().map(|c| c.id.clone()).collect::<Vec<_>>().join(", ");
            let one = unproven.len() == 1;
            return Check::new(
                "themes",
                label,
                Status::Info,
                if one {
                    format!("One theme check could not prove its result: {ids}.")
                } else {
                    format!("{} theme checks could not prove their results: {ids}.", unproven.len())
                },
            )
            .fix(if one { format!("See the {ids} check.") } else { format!("See each of these checks: {ids}.") });
        }
        return Check::new("themes", label, Status::Pass, "App themes come from the generated theme module, and every theme check passes.");
    }
    let run = env::invocation(cwd);
    let packages = list_theme_packages(cwd);
    if packages.is_empty() && !wiring.wired.is_empty() {
        return Check::new("themes", label, Status::Pass, format!("Themes wired by import: {}.", wired_list(&wiring.wired)));
    }
    if packages.is_empty() {
        return Check::new("themes", label, Status::Warn, "No @astryxdesign/theme-* packages are installed.").fix(format!(
            "Install a theme, e.g. `npm install @astryxdesign/theme-neutral`, then add it to the app with `{run} theme add neutral`."
        ));
    }
    let names = packages.join(", ");
    let named = app_package_names_theme(cwd);
    if !named && !wiring.wired.is_empty() {
        return Check::new("themes", label, Status::Pass, format!("Theme package(s) installed ({names}); wired by import: {}.", wired_list(&wiring.wired)));
    }
    if !named && !wiring.unconfirmed.is_empty() {
        let n = wiring.unconfirmed.len();
        return Check::new(
            "themes",
            label,
            Status::Info,
            format!(
                "Theme package(s) installed ({names}); {} pass{} a theme to Theme that doctor could not trace to a theme import, so it could not confirm which theme is wired.",
                wiring.unconfirmed.join(", "),
                if n == 1 { "es" } else { "" }
            ),
        )
        .fix(format!("If no theme is applied, add one with `{run} theme add <slug>`."));
    }
    if !named {
        return Check::new("themes", label, Status::Warn, format!("Theme package(s) installed ({names}) but no theme appears wired."))
            .fix(format!("Add one to the app with `{run} theme add <slug>`."));
    }
    Check::new("themes", label, Status::Pass, format!("Theme package(s) installed ({names}); wired via package.json astryx.theme."))
}

/// `checkAppThemes(cwd)`.
pub fn check_app_themes(cwd: &str) -> Vec<Check> {
    let state = match read_theme_state(cwd) {
        Ok(s) => s,
        Err(e) => {
            if e.contains("No package.json found") {
                return unavailable("No app theme record found.", None);
            }
            return unavailable("Skipped because the generated theme module could not be read.", Some(&e));
        }
    };
    if !state.configured {
        if let Err(e) = resolve_theme_module(&state.project_dir, true) {
            return unavailable("Skipped because the generated theme module is unavailable.", Some(&e));
        }
        let run = env::invocation(&state.project_dir);
        let mut report = vec![Check::new(
            "theme-management",
            "CLI-managed app themes",
            Status::Info,
            match &state.legacy_theme {
                Some(t) => format!(
                    "The CLI manages no themes. The released package.json astryx.theme value {} remains active.",
                    crate::json::stringify(&Value::String(t.clone()), 0)
                ),
                None => "The CLI manages no themes because this project has no generated theme module.".into(),
            },
        )
        .fix(format!("Start managing app themes with `{run} theme add <slug>`."))];
        if let Some(m) = unmigrated_copy_check(&state.project_dir) {
            report.push(m);
        }
        return report;
    }
    match crate::commands::theme::state::read(cwd) {
        Ok(st) if st.configured => super::themes_app::managed_checks(&st),
        Ok(_) => unavailable("Could not regenerate the module until its owners, imports, and default are valid.", None),
        Err(e) => unavailable("Skipped because the generated theme module could not be read.", Some(&e.0)),
    }
}

fn unmigrated_copy_check(project_dir: &str) -> Option<Check> {
    super::themes_app::unmigrated_copy_check(project_dir)
}
