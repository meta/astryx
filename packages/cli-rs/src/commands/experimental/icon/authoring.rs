pub const THEME_MAP_NAME: &str = "themeIcons";
const REACT_IMPORT: &str = "import {createElement} from 'react'";
const DEFAULT_ICON_SETS_ROOT: &str = "./icon-sets";
const ICON_SETS_ROOT_KEY: &str = "experimental.iconSets";

const GENERATED_HEADER: [&str; 4] = [
    "// Generated by `astryx experimental icon` (new-set, add, map): one export per icon of this set.",
    "// Edit with those commands; a statement added by hand is kept.",
    "// themeIcons has one entry per built-in icon definition in map (the names Core renders), not one per icon;",
    "// the import lines above it give it local names for the re-exported icons.",
];

const DATA_KEYS: [&str; 11] =
    ["schemaVersion", "module", "source", "exclude", "generated", "adapter", "variants", "default", "themeMap", "map", "icons"];

fn add_err(e: ih::AddError) -> IconError {
    ierr(e.message, e.suggestions.into_iter().map(|(n, r)| crate::cli::command::Suggestion::new(n, r)).collect(), e.code.as_deref().unwrap_or("ERR_UNKNOWN"))
}

/// `iconSetDataText(data)`: known keys in order (`map` sorted), then the rest.
pub fn icon_set_data_text(data: &Value) -> String {
    let empty = Map::new();
    let m = data.as_object().unwrap_or(&empty);
    let mut ordered = Map::new();
    for k in DATA_KEYS {
        let Some(v) = m.get(k) else { continue };
        if crate::discovery::docmod::is_undefined(Some(v)) {
            continue;
        }
        if k == "map" {
            let mut entries: Vec<(String, Value)> =
                v.as_object().map(|o| o.iter().map(|(a, b)| (a.clone(), b.clone())).collect()).unwrap_or_default();
            entries.sort_by(|a, b| crate::discovery::jsort::cmp_utf16(&a.0, &b.0));
            ordered.insert(k.into(), Value::Object(entries.into_iter().collect()));
        } else {
            ordered.insert(k.into(), v.clone());
        }
    }
    for (k, v) in m {
        if !DATA_KEYS.contains(&k.as_str()) {
            ordered.insert(k.clone(), v.clone());
        }
    }
    format!("{}\n", crate::json::stringify(&Value::Object(ordered), 2))
}

/// `generatedTypesPath(generated)`.
pub fn generated_types_path(generated: &str) -> Option<String> {
    for e in [".ts", ".tsx", ".mts", ".mtsx"] {
        if generated.ends_with(e) {
            return None;
        }
    }
    if let Some(s) = generated.strip_suffix(".mjs") {
        return Some(format!("{s}.d.mts"));
    }
    if let Some(s) = generated.strip_suffix(".cjs") {
        return Some(format!("{s}.d.cts"));
    }
    if let Some(s) = generated.strip_suffix(".jsx") {
        return Some(format!("{s}.d.ts"));
    }
    if let Some(s) = generated.strip_suffix(".js") {
        return Some(format!("{s}.d.ts"));
    }
    Some(generated.to_string())
}

/// `generatedModuleText` for a module written fresh with no icons: the
/// React import and an empty theme map (or nothing without a theme map).
pub fn fresh_generated_text(data: &Value, generated: &str) -> (String, Option<String>) {
    let theme = data.get("themeMap").and_then(|v| v.as_str()) == Some(THEME_MAP_NAME);
    let mut js: Vec<String> = GENERATED_HEADER.iter().map(|s| s.to_string()).collect();
    if theme {
        js.push(format!("{REACT_IMPORT};"));
        js.push(format!("export const {THEME_MAP_NAME} = {{}};"));
    }
    js.push(String::new());
    let dts = generated_types_path(generated).map(|_| {
        let mut l: Vec<String> = GENERATED_HEADER.iter().map(|s| s.to_string()).collect();
        if theme {
            l.push("import type {ReactElement} from 'react';".into());
            l.push(format!("export declare const {THEME_MAP_NAME}: {{}};"));
        }
        l.push(String::new());
        l.join("\n")
    });
    (js.join("\n"), dts)
}

/// `quoteJs(value)`: a single-quoted JS string literal.
pub fn quote_js(v: &str) -> String {
    format!("'{}'", v.replace('\\', "\\\\").replace('\'', "\\'").replace('\n', "\\n").replace('\r', "\\r"))
}

/// `peerNote(pkg)`.
pub fn peer_note(pkg: &Value) -> Option<String> {
    let cli = crate::cli::env::cli_version();
    let wanted = [("react", ">=18".to_string(), false), ("@types/react", ">=18".to_string(), true), ("@astryxdesign/cli", format!(">={cli}"), true)];
    let missing: Vec<&(&str, String, bool)> = wanted
        .iter()
        .filter(|(n, _, _)| crate::discovery::docmod::is_nullish(pkg.get("peerDependencies").and_then(|p| p.get(*n))))
        .collect();
    if missing.is_empty() {
        return None;
    }
    let peers: Vec<String> = missing.iter().map(|(n, r, _)| format!("\"{n}\": \"{r}\"")).collect();
    let optional: Vec<String> = missing.iter().filter(|m| m.2).map(|(n, _, _)| format!("\"{n}\": {{\"optional\": true}}")).collect();
    Some(format!(
        "Declare the peers your set needs; add to package.json \"peerDependencies\": `{{{}}}`{}.",
        peers.join(", "),
        if optional.is_empty() { String::new() } else { format!(" and to \"peerDependenciesMeta\": `{{{}}}`", optional.join(", ")) }
    ))
}

/// `typecheckNote(pkg)`.
pub fn typecheck_note(pkg: &Value) -> Option<String> {
    if !crate::discovery::docmod::is_nullish(pkg.get("scripts").and_then(|s| s.get("typecheck"))) {
        return None;
    }
    Some("Run `integration check --strict` in your build; add to package.json \"scripts\": `\"typecheck\": \"astryx integration check --strict\"`.".into())
}

fn rel(dir: &str, file: &str) -> String {
    np::relative(dir, file)
}

/// `entryWiringNote(packageDir, pkg, generated)`, for the package's own
/// module and the theme map.
pub fn entry_wiring_note(package_dir: &str, pkg: &Value, generated: &str) -> Option<String> {
    entry_wiring_note_with(package_dir, pkg, generated, None, None)
}

/// `entryWiringNote(packageDir, pkg, generated, {module, name})`.
pub fn entry_wiring_note_with(package_dir: &str, pkg: &Value, generated: &str, module: Option<&str>, name: Option<&str>) -> Option<String> {
    let package_name = pkg.get("name").and_then(|v| v.as_str()).unwrap_or("");
    let module = module.unwrap_or(package_name);
    let name = name.unwrap_or(THEME_MAP_NAME);
    let target = {
        let mut t = generated.to_string();
        for e in [".cjsx", ".mjsx", ".ctsx", ".mtsx", ".cjs", ".mjs", ".cts", ".mts", ".jsx", ".tsx", ".js", ".ts"] {
            if let Some(s) = generated.strip_suffix(e) {
                t = format!("{s}.js");
                break;
            }
        }
        t
    };
    let entry = if module.is_empty() { None } else { isd::resolve_icon_module(module, package_dir, Some(package_name), Some(package_dir)) };
    if let Some(e) = &entry {
        if crate::discovery::module_exports::module_exports_name(Path::new(e), name) {
            return None;
        }
    }
    let line_for = |from: &str| -> String {
        let mut r = np::relative(&np::dirname(from), &np::join2(package_dir, &target));
        if !r.starts_with('.') {
            r = format!("./{r}");
        }
        format!("export * from '{r}';")
    };
    let inside = |file: &str| {
        let r = np::relative(package_dir, file);
        !r.starts_with("..") && !np::is_absolute(&r) && !r.split('/').any(|s| s == "node_modules")
    };
    let Some(entry) = entry else {
        let absent = |k: &str| pkg.get(k).is_none();
        if absent("exports") && absent("main") && !np::exists(&np::join2(package_dir, "index.js")) {
            let line = line_for(&np::join2(package_dir, "index.js"));
            let files = if pkg.get("files").is_some_and(|f| f.is_array()) { " Add \"index.js\" and \"index.d.ts\" to \"files\"." } else { "" };
            return Some(format!("\"{module}\" has no entry, so its icons cannot be imported by name. Create index.js and index.d.ts, each with `{line}`, and add to package.json: `\"main\": \"./index.js\", \"types\": \"./index.d.ts\", \"exports\": {{\".\": {{\"types\": \"./index.d.ts\", \"default\": \"./index.js\"}}}}`.{files}"));
        }
        return Some(format!("\"{module}\" does not resolve: point its package.json \"exports\" at a file that has `export * from '{target}';` (relative to that file), or build the package."));
    };
    if !inside(&entry) || is_built_or_common_js(package_dir, &entry) {
        return Some(format!(
            "{} is built or CommonJS, so the CLI names no file to edit: add `export * from '{target}';` (relative to that file) to the source module your build compiles into it, and to its types, then build, so the icons and `{THEME_MAP_NAME}` import from {module}.",
            if inside(&entry) { rel(package_dir, &entry) } else { format!("\"{module}\"") }
        ));
    }
    let root_export = pkg.get("exports").filter(|e| e.is_object()).and_then(|e| e.get("."));
    let types_path = pkg
        .get("types")
        .and_then(|v| v.as_str())
        .filter(|s| !s.is_empty())
        .or_else(|| pkg.get("typings").and_then(|v| v.as_str()).filter(|s| !s.is_empty()))
        .or_else(|| root_export.filter(|r| r.is_object()).and_then(|r| r.get("types")).and_then(|v| v.as_str()));
    let also = types_path
        .map(|t| np::resolve(&[package_dir, t]))
        .filter(|tf| {
            *tf != entry
                && inside(tf)
                && np::exists(tf)
                && !is_built_or_common_js(package_dir, tf)
                && !std::fs::read_to_string(tf).unwrap_or_default().contains(&line_for(tf))
        })
        .map(|tf| format!(" and `{}` to {}", line_for(&tf), rel(package_dir, &tf)))
        .unwrap_or_default();
    Some(format!("Add `{}` to {}{also}, so the icons import from {module}.", line_for(&entry), rel(package_dir, &entry)))
}

fn is_built_or_common_js(package_dir: &str, entry: &str) -> bool {
    let r = np::relative(package_dir, entry);
    let first = r.split('/').next().unwrap_or("");
    if first == "dist" || first == "build" {
        return true;
    }
    if entry.ends_with(".cjs") || entry.ends_with(".cts") {
        return true;
    }
    if entry.ends_with(".js") {
        let text = std::fs::read_to_string(entry).unwrap_or_default();
        let cjs = text.contains("require(") || text.contains("module.exports");
        let esm = text.lines().any(|l| l.trim_start().starts_with("export "));
        return cjs && !esm;
    }
    false
}

/// `resolveProjectTypeScript([dir])`: whether a TypeScript with a compiler
/// API resolves from `dir`. `Some(None)`: installed without the API (its
/// version); `Some(Some(()))`: usable; `None`: not installed.
pub fn project_typescript(dir: &str) -> Option<Option<String>> {
    let found = |name: &str| -> Option<(String, String)> {
        let pkg_dir = crate::discovery::paths::find_installed_package(dir, name, usize::MAX)?;
        let pkg = np::read_json(&np::join2(&pkg_dir, "package.json"))?;
        let v = pkg.get("version").and_then(|v| v.as_str()).filter(|s| !s.is_empty())?.to_string();
        Some((pkg_dir, v))
    };
    let mut unusable = None;
    if let Some((_, v)) = found("typescript") {
        let major: u32 = v.split('.').next().and_then(|m| m.parse().ok()).unwrap_or(0);
        if major < 7 {
            return Some(None);
        }
        unusable = Some(v);
    }
    if found("@typescript/typescript6").is_some() {
        return Some(None);
    }
    unusable.map(Some)
}

