fn fmt_cmd(cmd: &str, dir: &Path) -> String {
    crate::cli::env::format_cli_command_at(dir, cmd)
}

/// `renamedOutputMessage`.
pub fn renamed_output_message(slug: &str, kind: &str, exported: &Path, source: &Path, built_name: Option<&str>, pkg_dir: &Path) -> Option<String> {
    let built_name = built_name?;
    if built_name == slug {
        return None;
    }
    let ext = if kind == "module" { ".js" } else { ".css" };
    if basename(exported) == format!("{built_name}{ext}") {
        return None;
    }
    let built = rel(pkg_dir, &source.parent().unwrap_or(pkg_dir).join(format!("{built_name}{ext}")));
    Some(format!(
        "Theme \"{slug}\" {kind} is {}, but {} calls defineTheme with name: '{built_name}', so `{}` writes {built} instead and rebuilding never updates {}. Fix: point the package export that serves it at {built} after building, or set name: '{slug}' in {} and rebuild.",
        rel(pkg_dir, exported),
        basename(source),
        fmt_cmd(&format!("theme build {}", rel(pkg_dir, source)), pkg_dir),
        basename(exported),
        basename(source)
    ))
}

pub enum Wrapper {
    Ok,
    Reject { reason: String, rebuild: bool },
}

pub struct WrapperTheme<'a> {
    pub export_name: &'a str,
    pub stylesheet_file: Option<PathBuf>,
    pub font_stylesheet_file: Option<PathBuf>,
    pub pkg: &'a Value,
    pub package_dir: &'a Path,
}

fn real(p: &Path) -> Option<PathBuf> {
    std::fs::canonicalize(p).ok()
}

fn resolve_relative_js(spec: &str, from: &Path) -> Option<PathBuf> {
    if !spec.starts_with("./") && !spec.starts_with("../") {
        return None;
    }
    let base = super::add_helpers::normalize(&from.parent()?.join(spec));
    let cands = [base.clone(), PathBuf::from(format!("{}.js", base.display())), base.join("index.js")];
    cands.into_iter().find(|c| c.to_string_lossy().ends_with(".js") && c.is_file())
}

fn resolve_stylesheet_import(spec: &str, module: &Path, t: &WrapperTheme) -> Option<PathBuf> {
    if spec.starts_with("./") || spec.starts_with("../") {
        let f = super::add_helpers::normalize(&module.parent()?.join(spec));
        return if f.is_file() { real(&f) } else { None };
    }
    let name = t.pkg.get("name")?.as_str()?;
    let sub = spec.strip_prefix(&format!("{name}/"))?;
    let info = crate::commands::theme::imports::inspect_export(t.pkg, &t.package_dir.to_string_lossy(), &format!("./{sub}"));
    if info.exported {
        info.target.and_then(|p| real(Path::new(&p)))
    } else {
        None
    }
}

fn built_theme_binding(file: &Path) -> Option<String> {
    let src = std::fs::read_to_string(file).ok()?;
    let alloc = Allocator::default();
    let ret = Parser::new(&alloc, &src, SourceType::mjs()).parse();
    if !ret.diagnostics.is_empty() {
        return None;
    }
    for st in ret.program.body.iter() {
        if let Statement::ExportNamedDeclaration(e) = st {
            let _ = e;
        }
        if let Statement::ExportDeclaration(e) = st {
            if let Declaration::VariableDeclaration(v) = &e.declaration {
                return match v.declarations.first().map(|d| &d.id) {
                    Some(BindingPattern::BindingIdentifier(b)) => Some(b.name.to_string()),
                    _ => None,
                };
            }
        }
    }
    None
}

fn line_of(src: &str, offset: u32) -> usize {
    src[..offset as usize].matches('\n').count() + 1
}

fn module_export_name_str(n: &ModuleExportName) -> String {
    match n {
        ModuleExportName::IdentifierName(i) => i.name.to_string(),
        ModuleExportName::IdentifierReference(i) => i.name.to_string(),
        ModuleExportName::StringLiteral(s) => s.value.as_str().unwrap_or_default().to_string(),
    }
}

/// `ownStylesEntry(moduleFile, expected, theme)`.
pub fn own_styles_entry(module: &Path, expected: &str, t: &WrapperTheme) -> Option<Wrapper> {
    let ms = module.to_string_lossy();
    if !ms.ends_with(".js") && !ms.ends_with(".mjs") {
        return None;
    }
    let src = std::fs::read_to_string(module).ok()?;
    let alloc = Allocator::default();
    let ret = Parser::new(&alloc, &src, SourceType::mjs()).parse();
    if !ret.diagnostics.is_empty() {
        return None;
    }
    let body = &ret.program.body;
    let is_reexport = |st: &Statement| match st.as_module_declaration() {
        Some(ModuleDeclaration::ExportAllDeclaration(_)) | Some(ModuleDeclaration::ExportFromDeclaration(_)) => true,
        _ => false,
    };
    let reexports: Vec<usize> = body.iter().enumerate().filter(|(_, s)| is_reexport(s)).map(|(i, _)| i).collect();
    if reexports.is_empty() {
        return None;
    }
    let reject = |r: String| Some(Wrapper::Reject { reason: r, rebuild: false });
    if reexports.len() > 1 {
        return reject("it has more than one re-export".into());
    }
    if !ret.program.directives.is_empty() {
        return reject("it has a directive".into());
    }
    let own: Vec<PathBuf> = [&t.stylesheet_file, &t.font_stylesheet_file].iter().filter_map(|f| f.as_ref().and_then(|p| real(p))).collect();
    let mut imported: Vec<PathBuf> = Vec::new();
    for (i, st) in body.iter().enumerate() {
        if i == reexports[0] {
            continue;
        }
        let line = line_of(&src, st.span().start);
        let Some(ModuleDeclaration::ImportDeclaration(imp)) = st.as_module_declaration() else {
            return reject(format!("line {line} is neither a stylesheet import nor the re-export"));
        };
        let spec = imp.source.value.as_str().unwrap_or_default().to_string();
        let has_specs = imp.specifiers.as_ref().map(|s| !s.is_empty()).unwrap_or(false);
        let has_attrs = imp.with_clause.as_ref().map(|w| !w.with_entries.is_empty()).unwrap_or(false);
        if imp.import_kind.is_type() || has_specs || has_attrs || imp.phase.is_some() {
            return reject(format!("its import of {spec} is not a side-effect import"));
        }
        let file = resolve_stylesheet_import(&spec, module, t);
        match file {
            Some(f) if own.contains(&f) => {
                if imported.contains(&f) {
                    return reject(format!("it imports {spec} twice"));
                }
                imported.push(f);
            }
            _ => return reject(format!("{spec} is not the theme's own stylesheet or font stylesheet")),
        }
    }
    let st = &body[reexports[0]];
    let (from, reexported) = match st.as_module_declaration() {
        Some(ModuleDeclaration::ExportAllDeclaration(e)) => {
            let from = e.source.value.as_str().unwrap_or_default().to_string();
            let attrs = e.with_clause.as_ref().map(|w| !w.with_entries.is_empty()).unwrap_or(false);
            if e.export_kind.is_type() || attrs {
                return reject(format!("its re-export from {from} is not a plain re-export"));
            }
            if e.exported.is_some() {
                return reject(format!("it re-exports {from} as a namespace"));
            }
            (from, None)
        }
        Some(ModuleDeclaration::ExportFromDeclaration(e)) => {
            let from = e.source.value.as_str().unwrap_or_default().to_string();
            let attrs = e.with_clause.as_ref().map(|w| !w.with_entries.is_empty()).unwrap_or(false);
            if e.export_kind.is_type() || attrs {
                return reject(format!("its re-export from {from} is not a plain re-export"));
            }
            let specs = &e.specifiers;
            if specs.len() != 1 || specs[0].export_kind.is_type() || module_export_name_str(&specs[0].exported) != t.export_name {
                return reject(format!("it re-exports names other than {}", t.export_name));
            }
            (from, Some(module_export_name_str(&specs[0].local)))
        }
        _ => return None,
    };
    let Some(target) = resolve_relative_js(&from, module) else {
        return reject(format!("its re-export from {from} does not name a .js module"));
    };
    if read_norm(&target).as_deref() != Some(expected) {
        return Some(Wrapper::Reject { reason: from, rebuild: true });
    }
    if let Some(r) = reexported {
        if Some(&r) != built_theme_binding(&target).as_ref() {
            return reject(format!("it re-exports {r}, which is not the built theme"));
        }
    }
    Some(Wrapper::Ok)
}

/// A scratch `theme build` of `source` into `dir` (inside the package, so
/// the build's output confinement admits it). Returns the expected module
/// and stylesheet files, or the error message.
pub fn scratch_build(source: &Path, pkg_dir: &Path, dir: &Path, slug: &str) -> Result<Option<(PathBuf, PathBuf)>, String> {
    use crate::commands::theme_build::build_impl::{theme_build_internal, BuildOptions, Logger};
    std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
    let css = dir.join(format!("{slug}.css"));
    let cwd = pkg_dir.to_string_lossy().to_string();
    let cli_root = crate::cli::env::cli_root().to_string_lossy().to_string();
    let mut out = crate::cli::command::Out::new(true, pkg_dir.to_path_buf());
    let mut log = Logger { out: &mut out, silent: true };
    let opts = BuildOptions { out: Some(css.to_string_lossy().to_string()), check: false, icons_specifier: None };
    let mut pve = false;
    let receipt = theme_build_internal(&source.to_string_lossy(), &opts, &cwd, &cli_root, &mut log, false, None, &mut pve, None).map_err(|e| e.message)?;
    let Some(r) = receipt else { return Ok(None) };
    if r["type"] != "theme.build" {
        return Ok(None);
    }
    let mut module = dir.join(format!("{slug}.js"));
    if let Some(js) = r["data"]["outputs"]["js"].as_str() {
        let f = super::add_helpers::resolve(pkg_dir, js);
        if f.starts_with(dir) && f != dir {
            module = f;
        }
    }
    Ok(Some((module, css)))
}

pub fn read_normalized(file: &Path) -> String {
    read_norm(file).unwrap_or_default()
}
