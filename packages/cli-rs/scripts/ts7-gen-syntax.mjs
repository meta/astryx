#!/usr/bin/env node
// Generates src/ts7/syntax_tables.rs from a TypeScript 7 package: syntax kind
// numbers, each kind's child properties in encoding order, and the node tests
// that compare a single kind. Usage:
//   node scripts/ts7-gen-syntax.mjs <typescript-7 package dir>
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL, fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const tsDir = path.resolve(process.argv[2] ?? "");
const imp = rel => import(pathToFileURL(path.join(tsDir, rel)).href);
const { SyntaxKind } = await imp("dist/enums/syntaxKind.js");
const { NodeFlags } = await imp("dist/enums/nodeFlags.js");
const { childProperties } = await imp("dist/api/node/protocol.generated.js");
const version = JSON.parse(fs.readFileSync(path.join(tsDir, "package.json"), "utf8")).version;
const isSource = fs.readFileSync(path.join(tsDir, "dist/ast/is.generated.js"), "utf8");

const names = Object.keys(SyntaxKind).filter(k => isNaN(Number(k)));
const out = [];
out.push(`//! Generated by scripts/ts7-gen-syntax.mjs from TypeScript ${version}. Do not edit.`);
out.push("");
out.push("/// A syntax kind's number by its name (`SyntaxKind.Identifier`).");
out.push("pub fn kind(name: &str) -> Option<u32> {");
out.push("    Some(match name {");
for (const n of names) out.push(`        ${JSON.stringify(n)} => ${SyntaxKind[n]},`);
out.push("        _ => return None,");
out.push("    })");
out.push("}");
out.push("");
out.push("/// A syntax kind's name (the first name the enum gives the number).");
out.push("pub fn kind_name(kind: u32) -> &'static str {");
out.push("    match kind {");
const seen = new Set();
for (const n of names) {
  const v = SyntaxKind[n];
  if (seen.has(v)) continue;
  seen.add(v);
  out.push(`        ${v} => ${JSON.stringify(n)},`);
}
out.push('        _ => "",');
out.push("    }");
out.push("}");
out.push("");
out.push("/// The child properties of a kind, in the order the encoding stores them.");
out.push("pub fn child_properties(kind: u32) -> &'static [&'static str] {");
out.push("    match kind {");
for (const [k, props] of Object.entries(childProperties).sort((a, b) => Number(a[0]) - Number(b[0]))) {
  out.push(`        ${k} => &[${props.map(p => JSON.stringify(p)).join(", ")}],`);
}
out.push("        _ => &[],");
out.push("    }");
out.push("}");
out.push("");
out.push("/// The kinds a node test (`isIdentifier`) accepts, for the tests that only compare kinds.");
out.push("pub fn test_kinds(name: &str) -> Option<&'static [u32]> {");
out.push("    Some(match name {");
const re = /export function (\w+)\(node\) \{\n\s*return node\.kind === SyntaxKind\.(\w+);\n\}/g;
for (const m of isSource.matchAll(re)) out.push(`        ${JSON.stringify(m[1])} => &[${SyntaxKind[m[2]]}],`);
const sw = /export function (\w+)\(node\) \{\n\s*switch \(node\.kind\) \{\n((?:\s*case SyntaxKind\.\w+:\n)+)\s*return true;\n\s*default:\n\s*return false;\n\s*\}\n\}/g;
for (const m of isSource.matchAll(sw)) {
  const kinds = [...m[2].matchAll(/SyntaxKind\.(\w+)/g)].map(k => SyntaxKind[k[1]]);
  out.push(`        ${JSON.stringify(m[1])} => &[${kinds.join(", ")}],`);
}
out.push("        _ => return None,");
out.push("    })");
out.push("}");
out.push("");
for (const n of ["FirstToken", "LastToken", "FirstJSDocNode", "LastJSDocNode", "FirstKeyword", "LastKeyword", "FirstTypeNode", "LastTypeNode"]) {
  out.push(`pub const ${n.replace(/([a-z])([A-Z])/g, "$1_$2").toUpperCase()}: u32 = ${SyntaxKind[n]};`);
}
// Every enum the API ships, by group and member name.
const enumDir = path.join(tsDir, "dist/enums");
out.push("");
out.push("/// A member of one of TypeScript 7's enums (`TypeFlags.Union`).");
out.push("pub fn enum_value(group: &str, name: &str) -> Option<f64> {");
out.push("    Some(match (group, name) {");
for (const f of fs.readdirSync(enumDir).filter(f => /^[a-z]\w*\.js$/.test(f) && !f.endsWith(".enum.js")).sort()) {
  const mod = await import(pathToFileURL(path.join(enumDir, f)).href);
  for (const [group, values] of Object.entries(mod)) {
    if (typeof values !== "object" || values === null) continue;
    for (const [k, v] of Object.entries(values)) {
      if (typeof v !== "number" || !isNaN(Number(k))) continue;
      out.push(`        (${JSON.stringify(group)}, ${JSON.stringify(k)}) => ${v}.0,`);
    }
  }
}
// TypeScript's `TypeFormatFlags`, which TypeScript 7 reads by the same bits.
for (const [k, v] of Object.entries({ NoTruncation: 1, UseAliasDefinedOutsideCurrentScope: 1 << 14, InTypeAlias: 1 << 23, UseSingleQuotesForStringLiteralType: 1 << 28 })) {
  out.push(`        ("TypeFormatFlags", ${JSON.stringify(k)}) => ${v}.0,`);
}
out.push("        _ => return None,");
out.push("    })");
out.push("}");
out.push(`pub const NODE_FLAG_JSDOC: u32 = ${NodeFlags.JSDoc};`);
out.push(`pub const NODE_FLAG_REPARSED: u32 = ${NodeFlags.Reparsed};`);
fs.writeFileSync(path.join(here, "../src/ts7/syntax_tables.rs"), out.join("\n") + "\n");
console.log("wrote src/ts7/syntax_tables.rs");
