// Test oracle only: file-protection classify and the `ignore` matcher on a
// generated project. Usage: node scripts/protection-oracle.mjs <js-cli-root> <out.json>
import * as fs from 'node:fs';
import * as path from 'node:path';
import * as os from 'node:os';
import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
const [cliRoot, out] = process.argv.slice(2);
const {createFileProtectionResolver} = await import(pathToFileURL(path.join(cliRoot, 'foundation/fs/file-protection.mjs')).href);
const ignore = createRequire(path.join(cliRoot, 'package.json'))('ignore');
const root = path.join(os.tmpdir(), 'astryx-protection-fixture');
fs.rmSync(root, {recursive: true, force: true});
const w = (rel, text) => { const f = path.join(root, rel); fs.mkdirSync(path.dirname(f), {recursive: true}); fs.writeFileSync(f, text); };
w('.gitignore', 'dist/\n*.log\n!keep.log\nbuild\n/root-only.txt\nsrc/**/tmp\n\\#hash\n  \nfoo\\ \n');
w('src/.gitignore', '*.gen.ts\n!important.gen.ts\n');
w('.gitattributes', '[attr]gen linguist-generated\n*.snap gen\nvendor/** linguist-vendored\nsrc/legacy.ts -linguist-generated\n"spaced file.txt" linguist-generated=true\n');
w('src/.gitattributes', 'legacy.ts linguist-generated\n');
w('.hgignore', 'syntax: glob\n*.orig\ninclude:hg/more.hgignore\nre:^cache/\n');
w('hg/more.hgignore', 'syntax: regexp\n\\.bak$\n');
w('src/a.ts', '// @generated by tool\n// Command: pnpm gen\nexport const a = 1;\n');
w('src/b.ts', '/* Code generated by x. DO NOT EDIT. */\nexport {}\n');
w('src/c.py', '#!/usr/bin/env python\n# @partially-generated\n');
w('src/plain.ts', 'export const x = 1; // @generated later\n');
w('src/legacy.ts', 'x');
w('keep.log', ''); w('x.log', ''); w('a.snap', ''); w('vendor/lib/x.js', ''); w('spaced file.txt', '');
const files = ['src/a.ts', 'src/b.ts', 'src/c.py', 'src/plain.ts', 'src/legacy.ts', 'keep.log', 'x.log', 'dist/a.js', 'a/dist/b.js', 'build/x', 'root-only.txt', 'src/root-only.txt',
  'src/x/tmp', 'src/a.gen.ts', 'src/important.gen.ts', 'a.snap', 'vendor/lib/x.js', 'spaced file.txt', 'f.orig', 'g.bak', 'cache/x', 'node_modules/a/b.js', '.git/config',
  '.yarn/cache/x', '.pnp.cjs', '../outside.txt', '#hash', 'foo ', 'missing/new.ts'];
const resolver = createFileProtectionResolver(root);
const cases = files.map(f => { try { return {file: f, protections: resolver.classify(path.join(root, f))}; } catch (e) { return {file: f, error: e.message}; } });
const patterns = ['*.js', '!a.js', 'a/**/b', '**/foo', 'foo/', '/bar', 'x?y', '[abc].txt', '[z-a].txt', 'a\\*b', 'trailing\\ ', 'dir/*', 'dir/**', '**', 'a/**', '\\!bang', '#comment', '*'];
const paths = ['a.js', 'b.js', 'a/x/b', 'a/b', 'x/foo', 'foo', 'foo/x', 'x/foo/y', 'bar', 'x/bar', 'xzy', 'b.txt', 'z.txt', 'a*b', 'trailing ', 'dir/a', 'dir/a/b', 'q', '!bang', 'a/c'];
const ig = [];
for (const p of patterns) { const m = ignore({ignorecase: false}).add(p); ig.push({pattern: p, results: paths.map(x => { const t = m.test(x); return [x, t.ignored, t.unignored]; })}); }
fs.writeFileSync(out, JSON.stringify({root, cases, ignore: ig}, null, 1));
