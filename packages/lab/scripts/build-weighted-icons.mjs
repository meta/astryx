/**
 * Builds a weighted icon module from per-weight SVG files, keeping only the
 * icons (and optionally weights) a product uses:
 *
 *   node packages/lab/scripts/build-weighted-icons.mjs <source-dir> <out.ts> \
 *     [--icons=bell,check] [--weights=400,500,600]
 *
 * <source-dir> holds one folder per icon with one file per weight:
 * `bell/300.svg`, `bell/400.svg`, ... `bell/700.svg`.
 *
 * --icons    only these icons (e.g. the names a static usage scan found)
 * --weights  only the weights the product's type scale can reach; other
 *            weights show the nearest kept drawing
 *
 * The output exports one `<name>WeightedIcon` per icon. Weight switching
 * happens in CSS at runtime, so the set of drawings stays fully static.
 */

import fs from 'node:fs';
import path from 'node:path';
import {buildWeightedIcon, ICON_WEIGHTS} from '../src/SVGIcon/buildWeightedIcon.ts';

const [sourceDir, outFile, ...flags] = process.argv.slice(2);
if (sourceDir == null || outFile == null) {
  console.error('usage: build-weighted-icons.mjs <source-dir> <out.ts> [--icons=a,b] [--weights=400,500]');
  process.exit(1);
}
const flag = name => flags.find(f => f.startsWith(`--${name}=`))?.split('=')[1]?.split(',');
const onlyIcons = flag('icons');
const weights = flag('weights')?.map(Number);
if (weights?.some(w => !ICON_WEIGHTS.includes(w))) {
  console.error(`--weights must be among ${ICON_WEIGHTS.join(', ')}`);
  process.exit(1);
}

const identifier = name => name.replace(/[^A-Za-z0-9]+(.)?/g, (_, c) => (c ?? '').toUpperCase());
const names = fs
  .readdirSync(sourceDir, {withFileTypes: true})
  .filter(entry => entry.isDirectory() && (onlyIcons == null || onlyIcons.includes(entry.name)))
  .map(entry => entry.name)
  .sort();

const blocks = names.map(name => {
  const drawings = {};
  for (const weight of ICON_WEIGHTS) {
    const file = path.join(sourceDir, name, `${weight}.svg`);
    if (fs.existsSync(file)) {
      drawings[weight] = fs.readFileSync(file, 'utf8');
    }
  }
  const icon = buildWeightedIcon(name, drawings, weights ? {weights} : {});
  return `export const ${identifier(name)}WeightedIcon: WeightedIconDef = ${JSON.stringify(icon, null, 2)};`;
});

fs.writeFileSync(
  outFile,
  `// Generated by build-weighted-icons.mjs; do not edit by hand.\n\n` +
    `import type {WeightedIconDef} from '@astryxdesign/lab';\n\n` +
    blocks.join('\n\n') +
    '\n',
);
console.log(`${names.length} icons -> ${outFile}`);
