/**
 * @file weightProbe.ts
 * @input The inherited font-weight of an icon
 * @output A registered 380-byte "weight probe" font whose `1ch` grows with the font weight
 * @position Lets CSS read the surrounding font-weight; used by WeightedSVGIcon
 *
 * CSS cannot query `font-weight` directly: container style queries, `if()`
 * and `inherit()` only see custom properties. A font can, though. This font
 * has no visible glyphs and one variation axis (wght 1-1000). The advance of
 * its "0" glyph is 1000 + weight units per 1000-unit em, so with the probe as
 * an element's first font, `1ch` = (1000 + weight) / 1000 em. A container
 * whose width is `1ch` turns that into something container queries can test
 * (`width >= 1.45em` means weight >= 450), with no length division.
 *
 * Advance widths are the one thing every variable-font engine varies; x-height
 * (MVAR) is not applied by every engine. The 1000-unit offset keeps fallback
 * fonts (whose "0" is about 0.5-0.6em) out of every tested range, so until the
 * probe decodes, icons use their fallback weight.
 * The font is regenerated by `scripts/generate-weight-probe-font.py`.
 */

