/**
 * @file `theme build` of a file another command generates (its leading
 * comment carries that command's mark) builds it as any local theme, and a
 * missing file that command writes is called generated, naming the exact
 * command, never answered with a blank theme template.
 */

import {describe, it, expect, beforeEach, afterEach} from 'vitest';
import * as fs from 'node:fs';
import * as path from 'node:path';
import * as os from 'node:os';
import {runCli} from '../../../test-utils/run-cli.mjs';

const MARK =
  '// Written by `astryx experimental theme editor show d` after every build; do not edit it here.\n';

/** @type {string} */
let app;
beforeEach(() => {
  app = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'astryx-gen-')));
  fs.writeFileSync(path.join(app, 'package.json'), '{"name":"app"}');
  fs.mkdirSync(path.join(app, 'src/themes/d'), {recursive: true});
  fs.writeFileSync(
    path.join(app, 'src/themes/d/dTheme.ts'),
    `${MARK}export default { name: 'd', tokens: {} };\n`,
  );
  fs.writeFileSync(
    path.join(app, 'src/themes/d/dTheme.doc.mjs'),
    `${MARK}export default {source: './dTheme.ts'};\n`,
  );
});
afterEach(() => {
  fs.rmSync(app, {recursive: true, force: true});
});

describe('a generated theme source', () => {
  it('present, is built by theme build as any local theme is', async () => {
    const r = await runCli(
      ['--json', 'theme', 'build', 'src/themes/d/dTheme.ts'],
      {cwd: app},
    );
    expect(r.status, r.stdout).toBe(0);
    expect(fs.existsSync(path.join(app, 'src/themes/d/d.css'))).toBe(true);
  });

  it('missing, in a folder of generated files, is called generated', async () => {
    fs.rmSync(path.join(app, 'src/themes/d/dTheme.ts'));
    const r = await runCli(
      ['--json', 'theme', 'build', 'src/themes/d/dTheme.ts'],
      {cwd: app},
    );
    expect(r.status).toBe(1);
    const env = JSON.parse(r.stdout);
    expect(env.code).toBe('ERR_FILE_NOT_FOUND');
    expect(env.error).toContain('It is a generated file');
    expect(JSON.stringify(env.suggestions)).not.toContain('theme template');
    // The exact command the mark names.
    expect(env.suggestions[0].name).toMatch(
      / experimental theme editor show d$/,
    );
  });

  it("missing, beside a mark that names only the editor group, names the theme's own command", async () => {
    fs.mkdirSync(path.join(app, 'themes/t'), {recursive: true});
    fs.writeFileSync(
      path.join(app, 'themes/t/t.settings.ts'),
      '// Generated by `astryx experimental theme editor` from t.settings.json; do not edit.\nexport const tSettings = {};\n',
    );
    fs.writeFileSync(
      path.join(app, 'themes/t/t.css'),
      '/* @generated by `astryx theme build`\n * Source: themes/t/t.theme.ts\n */\n',
    );
    const r = await runCli(
      ['--json', 'theme', 'build', 'themes/t/t.theme.ts'],
      {cwd: app},
    );
    expect(r.status).toBe(1);
    const env = JSON.parse(r.stdout);
    expect(env.code).toBe('ERR_FILE_NOT_FOUND');
    expect(env.suggestions[0].name).toMatch(
      / experimental theme editor show t$/,
    );
  });

  it('a name no file there names (a typo) is only not found', async () => {
    const r = await runCli(
      ['--json', 'theme', 'build', 'src/themes/d/dTheem.ts'],
      {cwd: app},
    );
    expect(r.status).toBe(1);
    const env = JSON.parse(r.stdout);
    expect(env.code).toBe('ERR_FILE_NOT_FOUND');
    expect(env.error).not.toContain('generated');
    expect(JSON.stringify(env.suggestions)).not.toContain('editor show');
  });

  it('a theme source of your own still builds', async () => {
    fs.writeFileSync(
      path.join(app, 'own.theme.mjs'),
      "export default { name: 'own', tokens: {} };\n",
    );
    const r = await runCli(['--json', 'theme', 'build', 'own.theme.mjs'], {
      cwd: app,
    });
    expect(r.status, r.stdout).toBe(0);
  });
});
