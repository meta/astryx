/**
 * @file Writes foundation/fonts/fontsource-families.generated.mjs: the name of
 * every family Fontsource publishes, from its public index
 * (https://api.fontsource.org/v1/fonts). The editor reads a capitalized name
 * as a font family only when it is a real one; this list is that proof for
 * the families Fontsource serves. The file is committed; run
 * `pnpm -F @astryxdesign/cli generate:font-families` to refresh it.
 */

import * as fs from 'node:fs';
import * as path from 'node:path';
import {CLI_ROOT} from '../foundation/fs/paths.mjs';

const SOURCE = 'https://api.fontsource.org/v1/fonts';
const OUT = path.join(
  CLI_ROOT,
  'foundation/fonts/fontsource-families.generated.mjs',
);

const response = await fetch(SOURCE);
if (!response.ok) {
  console.error(`${SOURCE} answered ${response.status}; nothing was written.`);
  process.exit(1);
}
const fonts = /** @type {Array<{family?: unknown}>} */ (await response.json());
const families = [
  ...new Set(
    fonts
      .map(font => (typeof font.family === 'string' ? font.family.trim() : ''))
      .filter(Boolean),
  ),
].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
if (families.length < 1000) {
  console.error(
    `${SOURCE} listed only ${families.length} families; nothing was written.`,
  );
  process.exit(1);
}
fs.writeFileSync(
  OUT,
  `// Copyright (c) Meta Platforms, Inc. and affiliates.
// @generated by scripts/generate-fontsource-families.mjs from ${SOURCE}; do not edit.
// Refresh: pnpm -F @astryxdesign/cli generate:font-families

/** Every family Fontsource publishes, by name. */
export const FONTSOURCE_FAMILIES = Object.freeze(${JSON.stringify(families, null, 0).replace(/","/g, '",\n  "').replace(/^\[/, '[\n  ').replace(/\]$/, ',\n]')});
`,
);
console.log(
  `Wrote ${families.length} families to ${path.relative(CLI_ROOT, OUT)}.`,
);
