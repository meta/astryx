function generatedCssArtifact({
  source = 'themes/ocean/oceanTheme.ts',
  cli = '0.6.6',
  core = '0.6.6',
  body = ':root { color: red; }',
} = {}) {
  return `/*
 * @generated by \`astryx theme build\` — do not edit manually.
 * Source: ${source}
 * Command: astryx theme build ${source}
 * CLI: @astryxdesign/cli@${cli}
 * Core: @astryxdesign/core@${core}
 */

${body}
`;
}

