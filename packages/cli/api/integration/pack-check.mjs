const GENERATED_HEADER_LINE =
  ' * @generated by `astryx theme build` — do not edit manually.';
const SOURCE_LINE = /^( \* Source: )(\S(?:.*\S)?)(\s*)$/u;
const CLI_VERSION_LINE = /^( \* CLI: @astryxdesign\/cli@)(\S+)(\s*)$/u;
const CORE_VERSION_LINE = /^( \* Core: @astryxdesign\/core@)(\S+)(\s*)$/u;

/**
 * Compare generated theme outputs without making their build directory or
 * CLI/Core version look like source drift. Normalization applies only to the
 * first generated JS or CSS comment and only when it contains exactly one
 * well-formed Source, CLI, and Core line. Missing, duplicate, malformed,
 * reordered, or any other bytes stay significant. `theme build --check`
 * deliberately stays strict.
 * @param {string} content
 */
export function normalizeThemeVerifyForCompare(content) {
  const normalized = normalizeThemeBuildForCompare(content);
  const lines = normalized.split('\n');
  if (lines[0] !== '/*' && lines[0] !== '/**') return normalized;
  const close = lines.indexOf(' */', 1);
  if (close === -1) return normalized;
  const header = lines.slice(1, close);
  if (header.filter(line => line === GENERATED_HEADER_LINE).length !== 1) {
    return normalized;
  }
  const source = header.filter(line => SOURCE_LINE.test(line));
  const cli = header.filter(line => CLI_VERSION_LINE.test(line));
  const core = header.filter(line => CORE_VERSION_LINE.test(line));
  if (source.length !== 1 || cli.length !== 1 || core.length !== 1) {
    return normalized;
  }
  return lines
    .map((line, index) => {
      if (index >= close) return line;
      if (SOURCE_LINE.test(line)) {
        return line.replace(SOURCE_LINE, '$1<source>$3');
      }
      if (CLI_VERSION_LINE.test(line)) {
        return line.replace(CLI_VERSION_LINE, '$1<version>$3');
      }
      if (CORE_VERSION_LINE.test(line)) {
        return line.replace(CORE_VERSION_LINE, '$1<version>$3');
      }
      return line;
    })
    .join('\n');
}

/**
 * Cleanup must never hide the check result or prevent the other temporary tree
 * from being removed.
 * @param {string|null} dir
 * @param {string} label
 * @param {Issue[]} issues
 */
function removeTreeBestEffort(dir, label, issues) {
  if (dir == null) return;
  try {
    fs.rmSync(dir, {recursive: true, force: true});
  } catch (err) {
    issues.push(
      warning(
        'cleanup_failed',
        `Could not remove ${label} ${dir}: ${err instanceof Error ? err.message : String(err)}`,
      ),
    );
  }
}

/**
 * Find the nearest package.json starting from `cwd` and walking up.
 * @param {string} cwd
 * @returns {{packageDir: string, pkg: Record<string, unknown>}|null}
 */
function findPackage(cwd) {
  let dir = path.resolve(cwd);
  for (let depth = 0; depth < 50; depth++) {
    const file = path.join(dir, 'package.json');
    if (fs.existsSync(file)) {
      try {
        return {
          packageDir: dir,
          pkg: JSON.parse(fs.readFileSync(file, 'utf-8')),
        };
      } catch (err) {
        throw new Error(
          `Could not parse ${file}: ${err instanceof Error ? err.message : String(err)}`,
          {cause: err},
        );
      }
    }
    const parent = path.dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }
  return null;
}

