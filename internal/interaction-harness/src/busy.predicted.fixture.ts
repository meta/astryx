/** One recorded cast: times are ms after the block began, positions CSS px. */
export interface RecordedZoomCast {
  readonly block: {
    readonly from: number;
    readonly to: number;
    readonly spanMs: number;
  };
  readonly animation: {
    readonly from: number;
    readonly to: number;
    readonly holds: boolean;
  };
  /** The replayed top edge, `[epoch ms, y]`, every 8 ms. */
  readonly geometry: ReadonlyArray<readonly [number, number]>;
  readonly controlStarts: readonly [number, number];
  /** Per frame: time, the photo's top edge and height. */
  readonly frames: ReadonlyArray<
    readonly [number, number | null, number | null]
  >;
  /** Per frame: time and each control's x. */
  readonly control: ReadonlyArray<readonly [number, number | null]>;
  readonly ahead: ReadonlyArray<readonly [number, number | null]>;
}

/**
 * Rows written one after another, a space between rows and a comma between
 * values. An empty value is a frame the marker did not show in.
 */
function rows<T extends ReadonlyArray<number | null>>(text: string): T[] {
  return text
    .trim()
    .split(/\s+/)
    .map(
      row =>
        row.split(',').map(v => (v === '' ? null : Number(v))) as unknown as T,
    );
}

